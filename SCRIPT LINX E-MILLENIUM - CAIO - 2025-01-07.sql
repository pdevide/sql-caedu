CREATE OR ALTER TRIGGER LXD_VENDAS ON VENDAS
FOR DELETE NOT FOR REPLICATION
AS
begin

	Declare	@errmsg varchar(255);

    IF EXISTS (
        SELECT 1
        FROM deleted
        WHERE PEDIDO_IMP_MILEN = 'T'
    )
    BEGIN
        /* Lança um erro e impede a exclusão */
		select @errmsg = 'Exclusão não permitida: O pedido já foi importado para o Millennium.';
        goto error;
    END

	return
Error:
	raiserror (@errmsg, 16, 1)
	rollback transaction
End
go

