						A.ID_VENDA_ENTREGA_FUTURA,A.PRODUTO, A.COR_PRODUTO,A.PRECO1, C.DESCONTO_ITEM, C.TAMANHO, C.CODIGO_BARRA  
					UNION ALL   
					SELECT  
						A.ID_VENDA_ENTREGA_FUTURA, SUM(A.QTDE_CANCELADA) AS QTDE, A.PRODUTO, A.COR_PRODUTO,  
						A.PRECO1, C.DESCONTO_ITEM, C.TAMANHO, C.CODIGO_BARRA  
					FROM  
						DELETED A  
						JOIN LJ_VENDA_ENTREGA_FUTURA B ON A.ID_VENDA_ENTREGA_FUTURA = B.ID_VENDA_ENTREGA_FUTURA  
						JOIN LOJA_VENDA_PRODUTO C ON B.CODIGO_FILIAL = C.CODIGO_FILIAL AND B.TICKET = C.TICKET AND B.DATA_VENDA = C.DATA_VENDA AND B.ITEM = C.ITEM   
					GROUP BY   
						A.ID_VENDA_ENTREGA_FUTURA,A.PRODUTO, A.COR_PRODUTO,A.PRECO1, C.DESCONTO_ITEM, C.TAMANHO, C.CODIGO_BARRA) A 
				GROUP BY  
					ID_VENDA_ENTREGA_FUTURA, PRODUTO, COR_PRODUTO, PRECO1, TAMANHO, CODIGO_BARRA  
				HAVING SUM(QTDE) != 0    

			OPEN CUR_VENDAS  
			FETCH NEXT FROM CUR_VENDAS INTO @ID_VENDA_ENTREGA_FUTURA, @QTDE, @PRODUTO, @COR_PRODUTO, @PRECO, @DESCONTO, @TAMANHO, @CODIGO_BARRA  

			WHILE @@FETCH_STATUS = 0    
			BEGIN  
			 
				UPDATE   
					LJ_VENDA_ENTREGA_FUTURA  
				SET   
					QTDE_CANCELADA =  @QTDE * -1, QTDE_ENTREGAR = 0, QTDE_ENTREGUE = 0   
