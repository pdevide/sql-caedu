CREATE or alter FUNCTION [dbo].[EML_DATA_MILLISEGUNDOS]	
(@DATA_PARA_TRANSFERENCIA DATETIME,@MILLISEGUNDOS VARCHAR(20))
	RETURNS DATETIME
AS 
BEGIN
	DECLARE	@DATA_COMPLETA	DATETIME
	DECLARE @DIA			VARCHAR(2)
	DECLARE @MES			VARCHAR(2)
	DECLARE @ANO			VARCHAR(4)
	DECLARE @HORA			VARCHAR(2)
	DECLARE @MINUTO			VARCHAR(2)
	DECLARE @SEGUNDO		VARCHAR(2)

	SELECT @DIA = DATEPART(DAY,@DATA_PARA_TRANSFERENCIA)
	SELECT @MES = DATEPART(MONTH,@DATA_PARA_TRANSFERENCIA)
	SELECT @ANO = DATEPART(YEAR,@DATA_PARA_TRANSFERENCIA)
	SELECT @HORA = DATEPART(HOUR,@DATA_PARA_TRANSFERENCIA)
	SELECT @MINUTO = DATEPART(MINUTE,@DATA_PARA_TRANSFERENCIA)
	SELECT @SEGUNDO = DATEPART(SECOND,@DATA_PARA_TRANSFERENCIA)

	SELECT @DATA_COMPLETA = CONVERT(DATETIME,@ANO + '-' + @MES + '-' + @DIA + ' ' + @HORA + ':' + @MINUTO + ':' + @SEGUNDO + '.' + @MILLISEGUNDOS)

	RETURN @DATA_COMPLETA 

END
go

