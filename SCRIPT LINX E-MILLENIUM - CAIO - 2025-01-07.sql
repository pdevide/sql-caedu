					NULL, NULL, NULL, PERIODO_FECHAMENTO, SUGESTAO_COD_FORMA_PGTO,   
					NULL, NULL, CPF_CGC_ECF  
				FROM   
					LOJA_VENDA A  
					INNER JOIN LOJA_VENDA_PRODUTO B ON A.CODIGO_FILIAL = B.CODIGO_FILIAL AND A.TICKET = B.TICKET AND A.DATA_VENDA = B.DATA_VENDA   
					INNER JOIN LJ_VENDA_ENTREGA_FUTURA C ON B.CODIGO_FILIAL = C.CODIGO_FILIAL AND B.TICKET = C.TICKET AND B.DATA_VENDA = C.DATA_VENDA AND B.ITEM = C.ITEM  
				WHERE  
					A.TICKET = @TICKET_OLD AND A.CODIGO_FILIAL = @CODIGO_FILIAL AND A.DATA_VENDA = @DATA_VENDA  
				GROUP BY  
					VENDEDOR, OPERACAO_VENDA, CODIGO_TAB_PRECO, TERMINAL, GERENTE_LOJA, GERENTE_PERIODO,    
					PERIODO_FECHAMENTO, SUGESTAO_COD_FORMA_PGTO, CPF_CGC_ECF  
			END     

			DECLARE CUR_VENDAS CURSOR   
			FOR   

				SELECT 
					ID_VENDA_ENTREGA_FUTURA, SUM(QTDE), PRODUTO, COR_PRODUTO, PRECO1, SUM(DESCONTO_ITEM), TAMANHO, CODIGO_BARRA  
				FROM  
					(SELECT   
						A.ID_VENDA_ENTREGA_FUTURA, (SUM(A.QTDE_CANCELADA) *-1) AS QTDE, A.PRODUTO, A.COR_PRODUTO,   
						A.PRECO1, C.DESCONTO_ITEM, C.TAMANHO, C.CODIGO_BARRA  
					FROM  
						INSERTED A  
						JOIN LJ_VENDA_ENTREGA_FUTURA B ON A.ID_VENDA_ENTREGA_FUTURA = B.ID_VENDA_ENTREGA_FUTURA  
						JOIN LOJA_VENDA_PRODUTO C ON B.CODIGO_FILIAL = C.CODIGO_FILIAL AND B.TICKET = C.TICKET AND B.DATA_VENDA = C.DATA_VENDA AND B.ITEM = C.ITEM   
