					ID_VENDA_ENTREGA_FUTURA = @ID_VENDA_ENTREGA_FUTURA  
				     
				SET @ITEM = RIGHT(REPLICATE('0', 4) + CONVERT(VARCHAR, @CONTADOR), 4)   
				  
				INSERT INTO 
					LOJA_VENDA_TROCA (TICKET, CODIGO_FILIAL, ITEM, DATA_VENDA, CODIGO_BARRA, PRODUTO, COR_PRODUTO, TAMANHO, QTDE, PRECO_LIQUIDO, INDICA_ENTREGA_FUTURA, NAO_MOVIMENTA_ESTOQUE)  
				VALUES
					(@TICKET, @CODIGO_FILIAL, @ITEM, CONVERT(VARCHAR(10),GETDATE(),112), @CODIGO_BARRA, @PRODUTO, @COR_PRODUTO, @TAMANHO, @QTDE*-1, @PRECO,  1, 1)  
			 
				UPDATE   
					 LOJA_VENDA  
				SET  
				 VALOR_PAGO = (VALOR_PAGO + (@QTDE*@PRECO)) , VALOR_TROCA = VALOR_TROCA + (@QTDE*@PRECO) *-1,   
				 QTDE_TROCA_TOTAL = QTDE_TROCA_TOTAL + (@QTDE *-1)
				WHERE 
					TICKET = @TICKET AND CODIGO_FILIAL = @CODIGO_FILIAL  
				
		 		SET @CONTADOR = @CONTADOR + 1  
			 
				FETCH NEXT FROM CUR_VENDAS  INTO @ID_VENDA_ENTREGA_FUTURA, @QTDE, @PRODUTO, @COR_PRODUTO, @PRECO, @DESCONTO, @TAMANHO, @CODIGO_BARRA  
			END   

			CLOSE CUR_VENDAS  
			DEALLOCATE CUR_VENDAS  
		END    

  RETURN
	ERROR:
    raiserror (@errmsg, 16, 1)
    ROLLBACK TRANSACTION
END
go

