CREATE or alter FUNCTION [dbo].[EML_DATA_VARCHAR]	
(@DATA_PARA_TRANSFERENCIA DATETIME)
	RETURNS varchar(200)
AS 
BEGIN
	DECLARE	@DATA_COMPLETA	varchar(200)
	DECLARE @DIA			VARCHAR(2)
	DECLARE @MES			VARCHAR(2)
	DECLARE @ANO			VARCHAR(4)
	DECLARE @HORA			VARCHAR(2)
	DECLARE @MINUTO			VARCHAR(2)
	DECLARE @SEGUNDO		VARCHAR(2)
	DECLARE @MILLISEGUNDOS	VARCHAR(3)

	SELECT @DIA = REPLICATE('0', 2 - LEN(DATEPART(DAY,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(DAY,@DATA_PARA_TRANSFERENCIA))
	SELECT @MES = REPLICATE('0', 2 - LEN(DATEPART(MONTH,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(MONTH,@DATA_PARA_TRANSFERENCIA))
	SELECT @ANO = DATEPART(YEAR,@DATA_PARA_TRANSFERENCIA)
	SELECT @HORA = REPLICATE('0', 2 - LEN(DATEPART(HOUR,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(HOUR,@DATA_PARA_TRANSFERENCIA))
	SELECT @MINUTO = REPLICATE('0', 2 - LEN(DATEPART(MINUTE,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(MINUTE,@DATA_PARA_TRANSFERENCIA))
	SELECT @SEGUNDO = REPLICATE('0', 2 - LEN(DATEPART(SECOND,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(SECOND,@DATA_PARA_TRANSFERENCIA))
	SELECT @MILLISEGUNDOS = REPLICATE('0', 3 - LEN(DATEPART(MILLISECOND,@DATA_PARA_TRANSFERENCIA))) + RTrim(DATEPART(MILLISECOND,@DATA_PARA_TRANSFERENCIA))

	SELECT @DATA_COMPLETA = (@ANO + @MES + @DIA + @HORA + @MINUTO + @SEGUNDO + @MILLISEGUNDOS)

	RETURN @DATA_COMPLETA 

END
GO
