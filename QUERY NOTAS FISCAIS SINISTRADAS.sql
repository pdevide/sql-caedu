select 
		F.FILIAL, 
		F.NF_SAIDA, 
		F.NOME_CLIFOR, 
		F.SERIE_NF, 
		F.EMISSAO, 
		F.CHAVE_NFE, 
		F.NATUREZA_SAIDA,
		FP.PRODUTO,
		FP.COR_PRODUTO,
		FP.QTDE, 
		FP.ITEM_IMPRESSAO,
		FP.DATA_PARA_TRANSFERENCIA,
		FP.CUSTO_NA_DATA,
		FP.VALOR,
		FP.PRECO,
		F1, F2, F3, F4, F5, F6, F7, F8, F9, F10, F11, F12, F13, F14, F15, F16,
		P.DESC_PROD_NF, P.DESC_PRODUTO, P.GRADE, P.ERP_QTD_PACK, pc.DESC_COR_PRODUTO,
		p.GRIFFE, p.LINHA, p.GRUPO_PRODUTO, p.SUBGRUPO_PRODUTO
from faturamento F
INNER JOIN FATURAMENTO_PROD FP 
	ON FP.FILIAL=F.FILIAL AND FP.NF_SAIDA=F.NF_SAIDA AND FP.SERIE_NF=F.SERIE_NF
INNER JOIN PRODUTOS P 
	ON P.PRODUTO = FP.PRODUTO
INNER JOIN PRODUTO_CORES pc 
	on pc.PRODUTO = fp.PRODUTO and pc.COR_PRODUTO = fp.COR_PRODUTO
where F.filial = 'CD CAJAMAR' 
AND CAST(F.NF_SAIDA AS INT) IN
(23558,23557,23559,23561,23564,23565,23567,23570,3843,42976,42958,3836,41945,3827)
