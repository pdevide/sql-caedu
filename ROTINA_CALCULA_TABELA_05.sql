--'CD ARAQUARI','CD ARAUARI','CD BARRA VELHA','CD CAJAMAR','CD NAVEGANTES','CD REGIS','ARAQUARI CQ','NAVEGANTES CQ','REJEITADO CQ','BARRA VELHA - CQ','CAJAMAR - CQ',
