create procedure CGP_MOVIMENTA_ESTOQUE_FILIAIS
	@FILIAL_ORIGEM VARCHAR(25),
	@FILIAL_DESTINO VARCHAR(25),
	@LISTA_SKU_QTD VARCHAR(4000),
	@TRANSFERIDO BIT OUTPUT
/*
PARAMETRO 1: @FILIAL_ORIGEM = 'CD CAJAMAR'
PARAMETRO 2: @FILIAL_DESTINO = 'VENDA ATACADO'
PARAMETRO 3: @LISTA_SKU_QTD = '123456789012345;15|987654321012345;70' --> SEPARARAR CODIGO DE BARRA 
																		DE QUANTIDADE COM DELIMITADOR ';' E USAR '|' 
																			COMO DELIMITADOR DE CONJUNTO DE DADOS
*/
AS

SET NOCOUNT ON
SET @TRANSFERIDO = 0
DECLARE @MATRIZ_FISCAL_ORIGEM VARCHAR(25), @MATRIZ_FISCAL_DESTINO VARCHAR(25), @MSG VARCHAR(1000)

SELECT @MATRIZ_FISCAL_ORIGEM=MATRIZ_FISCAL FROM FILIAIS WHERE FILIAL = @FILIAL_ORIGEM

SELECT @MATRIZ_FISCAL_DESTINO=MATRIZ_FISCAL FROM FILIAIS WHERE FILIAL = @FILIAL_DESTINO

IF NOT EXISTS(SELECT 1 FROM FILIAIS WHERE FILIAL = @FILIAL_ORIGEM) 
BEGIN
    SET @MSG ='FILIAL ORIGEM ' + @FILIAL_ORIGEM + ' NAO EXISTE!!!' 
	RAISERROR(@MSG,16,1)
	RETURN -1
END

IF NOT EXISTS(SELECT 1 FROM FILIAIS WHERE FILIAL = @FILIAL_DESTINO) 
BEGIN
    SET @MSG ='FILIAL DESTINO ' + @FILIAL_DESTINO + ' NAO EXISTE!!!' 
	RAISERROR(@MSG,16,1)
	RETURN -1
END

IF @MATRIZ_FISCAL_ORIGEM <> @MATRIZ_FISCAL_DESTINO
BEGIN
    SET @MSG ='MATRIZ FISCAL DA FILIAL_ORIGEM E DIFERENTE DA MATRIZ FISCAL DA FILIAL DESTINO!!!'
	RAISERROR(@MSG,16,1)
	RETURN -1
END

IF @FILIAL_ORIGEM = @FILIAL_DESTINO
BEGIN
    SET @MSG ='NAO E POSSIVEL TRANSFERIR ESTOQUE POIS AS FILIAIS DE ORIGEM E DESTINO SAO IGUAIS!!!'
	RAISERROR(@MSG,16,1)
	RETURN -1
END

DECLARE @TAB_ITENS TABLE (ID INT IDENTITY(1,1), PARTE1 VARCHAR(50), SKU VARCHAR(25), 
							PRODUTO VARCHAR(8), COR_PRODUTO VARCHAR(10), TAMANHO INT, QTD INT, ESTOQUE INT, DIFERENCA INT, ULT_CUSTO NUMERIC (18,6))

INSERT INTO @TAB_ITENS (PARTE1) 
select * from dbo.FX_SplitString(@LISTA_SKU_QTD,'|')

DECLARE		@I INT, @TOT INT, @PARTE1 VARCHAR(50), 
			@SKU VARCHAR(25), @QTD INT, @ESTOQUE INT, @DIFERENCA INT,
			@PRODUTO VARCHAR(8), @COR_PRODUTO VARCHAR(10), @TAMANHO INT, @ULT_CUSTO NUMERIC(18,6)

SELECT @I=MIN(ID), @TOT=MAX(ID) 
FROM @TAB_ITENS

WHILE @I<=@TOT
BEGIN
	SELECT @PARTE1 = PARTE1 
	FROM @TAB_ITENS 
	WHERE ID = @I
	
	SET @SKU = SUBSTRING(@PARTE1,1,charindex(';',@PARTE1,1)-1)
	SET @QTD = SUBSTRING(@PARTE1,charindex(';',@PARTE1,1)+1,50)

	SELECT @PRODUTO = PRODUTO, @COR_PRODUTO = COR_PRODUTO, @TAMANHO = TAMANHO
	FROM PRODUTOS_BARRA
	WHERE CODIGO_BARRA = @SKU
	
	SELECT @ESTOQUE = 
			CASE 
			WHEN @TAMANHO = 1 THEN ES1
			WHEN @TAMANHO = 2 THEN ES2
			WHEN @TAMANHO = 3 THEN ES3
			WHEN @TAMANHO = 4 THEN ES4
			WHEN @TAMANHO = 5 THEN ES5
			WHEN @TAMANHO = 6 THEN ES6
			WHEN @TAMANHO = 7 THEN ES7
			WHEN @TAMANHO = 8 THEN ES8
			WHEN @TAMANHO = 9 THEN ES9
			WHEN @TAMANHO = 10 THEN ES10
			WHEN @TAMANHO = 11 THEN ES11
			WHEN @TAMANHO = 12 THEN ES12
			WHEN @TAMANHO = 13 THEN ES13
			WHEN @TAMANHO = 14 THEN ES14
			WHEN @TAMANHO = 15 THEN ES15
			WHEN @TAMANHO = 16 THEN ES16
			ELSE 0
			END, 
			@ULT_CUSTO = ULTIMO_CUSTO1
	FROM ESTOQUE_PRODUTOS 
	WHERE	FILIAL=@FILIAL_ORIGEM 
			AND PRODUTO = @PRODUTO 
			AND COR_PRODUTO = @COR_PRODUTO

	UPDATE @TAB_ITENS
	SET SKU = @SKU, QTD = @QTD, ESTOQUE = @ESTOQUE, DIFERENCA = @ESTOQUE - @QTD, PRODUTO = @PRODUTO, 
		COR_PRODUTO=@COR_PRODUTO, TAMANHO = @TAMANHO, ULT_CUSTO = @ULT_CUSTO
	WHERE ID = @I

	SET @I=@I+1
END

IF EXISTS (SELECT 1 FROM @TAB_ITENS WHERE DIFERENCA<0)
BEGIN
    SET @MSG ='NAO E POSSIVEL EFETUAR A TRANSFERENCIA, POIS NAO HA SALDO DE ESTOQUE SUFICIENTE!!!'
	RAISERROR(@MSG,16,1)
	RETURN -1
END

