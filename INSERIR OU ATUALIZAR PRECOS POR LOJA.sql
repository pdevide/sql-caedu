select  @tot = count(*) from @tabprecos

declare	@codigo char(2),
		@produto char(8),
		@preco numeric(10,2)

set @i = 1
set @ins = 0
set @upd = 0

declare @datahoje varchar(10) 
set @datahoje = convert(varchar, getdate(), 112)

while @i <= @tot
begin
	
	select	@codigo = a.codigo,
			@produto = a.produto,
			@preco = a.preco
	from @tabprecos a
	where a.id = @i

	if not exists(select 1 from produtos_precos where CODIGO_TAB_PRECO=@codigo and PRODUTO=@produto)
	--INSERT
	BEGIN

		insert into produtos_precos (CODIGO_TAB_PRECO,PRODUTO,PRECO1,LX_STATUS_REGISTRO,DATA_PARA_TRANSFERENCIA,DATA_CARGA_PRECOS)
		values (@codigo, @produto, @preco, 0, @datahoje,@datahoje)

		set @ins = @ins + 1

	END
	--UPDATE
	ELSE
	BEGIN

		update produtos_precos 
		set CODIGO_TAB_PRECO =@codigo,
		PRODUTO = @produto,
		PRECO1 = @preco,
