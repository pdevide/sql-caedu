update a set UNOUS_NIVEL = 'FLEX'
from CAE_PRODUTOS_FATOR_P a
inner join PRODUTOS b 
	on b.GRIFFE=a.GRIFFE and b.LINHA=a.LINHA and b.GRUPO_PRODUTO=a.GRUPO_PRODUTO and b.SUBGRUPO_PRODUTO=a.SUBGRUPO_PRODUTO
inner join @produtos c on c.produto = b.PRODUTO


