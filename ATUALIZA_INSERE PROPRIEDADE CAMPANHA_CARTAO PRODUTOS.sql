	/*INFORMAÇÃO JÁ EXISTE - UPDATE*/
	IF EXISTS(SELECT 1 FROM PROP_PRODUTOS WHERE PROPRIEDADE = '00114' AND PRODUTO = @PRODUTO)
	BEGIN
		
		UPDATE PROP_PRODUTOS
		SET VALOR_PROPRIEDADE = @VALOR_PROP
		WHERE PROPRIEDADE = '00114' AND PRODUTO = @PRODUTO

		SET @TOTUPD = @TOTUPD + 1
	END
	ELSE
	/*INFORMAÇÃO NÃO EXISTE - INSERT*/
	BEGIN
		INSERT INTO PROP_PRODUTOS (PROPRIEDADE,PRODUTO,ITEM_PROPRIEDADE,VALOR_PROPRIEDADE,DATA_PARA_TRANSFERENCIA)
		VALUES ('00114',@PRODUTO,1,@VALOR_PROP,NULL)

		SET @TOTINS = @TOTINS + 1
	END
		
	SET @I = @I + 1
END

SELECT 'TOTAL =' AS TOTAL, @TOTINS AS INSERIDOS, @TOTUPD AS ATUALIZADOS
