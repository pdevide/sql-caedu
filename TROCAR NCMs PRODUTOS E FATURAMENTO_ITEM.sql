DECLARE @DE VARCHAR(8), @PARA VARCHAR(8), @ACAO INT, @QTPRO INT, @QTNF INT, @QTNCM INT 

SET @DE   = '61013000'
SET @PARA = '62014000'
SET @ACAO = 1 
SET @QTPRO = 0
SET @QTNF = 0
SET @QTNCM = 0

IF @ACAO=1
/* SELECT */
BEGIN

	select @QTPRO = COUNT(*) 
	from produtos P
	where P.classif_fiscal = @DE

	SELECT @QTNF = COUNT(*)
	FROM FATURAMENTO_ITEM FI
	INNER JOIN FATURAMENTO F ON F.NF_SAIDA=FI.NF_SAIDA AND F.SERIE_NF=FI.SERIE_NF AND F.FILIAL=FI.FILIAL
	WHERE FI.CLASSIF_FISCAL = @DE AND F.EMISSAO > '20220404'

	SELECT @QTNCM = COUNT(*) 
	FROM CLASSIF_FISCAL
	WHERE CLASSIF_FISCAL = @PARA
	
	SELECT @QTPRO AS QTPRO, @QTNCM AS NCM_PARA, @QTNF AS QTNF
	
	IF @QTPRO>0 AND @QTNCM>0
	BEGIN
		UPDATE PRODUTOS 
		SET CLASSIF_FISCAL = @PARA
		WHERE CLASSIF_FISCAL = @DE
	END

	IF @QTNF>0 AND @QTNCM>0
	BEGIN
		UPDATE FI SET CLASSIF_FISCAL = @PARA
		FROM FATURAMENTO_ITEM FI
		INNER JOIN FATURAMENTO F ON F.NF_SAIDA=FI.NF_SAIDA AND F.SERIE_NF=FI.SERIE_NF AND F.FILIAL=FI.FILIAL
		WHERE FI.CLASSIF_FISCAL = @DE AND F.EMISSAO > '20220404'
	END

END


