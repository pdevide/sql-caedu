select p.grade as grade_produto, 
		pb.CODIGO_BARRA,
		pb.produto, 
		pb.COR_PRODUTO, 
		pb.TAMANHO, 
		pb.grade as grade_sku,
		pb.INATIVO, 
		pb.CODIGO_BARRA_PADRAO,
        t.Tamanho as Grade_tamanho
from @tabela a
inner join produtos_barra pb on pb.produto = a.produto
inner join produtos p on p.produto = a.produto
left join (
SELECT
    pt.GRADE,
    v.Posicao       AS Tamanho_Posicao,
    v.TamanhoValor  AS Tamanho
FROM dbo.PRODUTOS_TAMANHOS AS pt
CROSS APPLY (
    VALUES
        (1,  pt.TAMANHO_1),
        (2,  pt.TAMANHO_2),
        (3,  pt.TAMANHO_3),
        (4,  pt.TAMANHO_4),
        (5,  pt.TAMANHO_5),
        (6,  pt.TAMANHO_6),
        (7,  pt.TAMANHO_7),
        (8,  pt.TAMANHO_8),
        (9,  pt.TAMANHO_9),
        (10, pt.TAMANHO_10),
        (11, pt.TAMANHO_11),
        (12, pt.TAMANHO_12),
        (13, pt.TAMANHO_13),
        (14, pt.TAMANHO_14),
        (15, pt.TAMANHO_15),
        (16, pt.TAMANHO_16)
) AS v(Posicao, TamanhoValor)
WHERE
    v.TamanhoValor IS NOT NULL
    AND LTRIM(RTRIM(v.TamanhoValor)) <> ''
) as t on t.GRADE = p.GRADE and t.Tamanho_Posicao=pb.TAMANHO
--where t.Tamanho_Posicao <> pb.GRADE
order by produto, cor_produto, tamanho