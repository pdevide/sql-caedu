SELECT NOME_CLIFOR, CGC_CPF, INATIVO, CLIFOR FROM CADASTRO_CLI_FOR 
WHERE CGC_CPF IN (
select a.CGC_CPF--, COUNT(*) AS QT
from CADASTRO_CLI_FOR a
inner join FILIAIS b on 
b.CLIFOR=a.CLIFOR
where b.CLIFOR in (select CODIGO_FILIAL from INFO_LOJAS)
group by a.CGC_CPF
HAVING COUNT(*)>1 ) 
AND CGC_CPF <> '27812909000109' AND INATIVO=0


