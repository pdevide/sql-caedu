DECLARE @MIN INT, @MAX INT, @FILIAL VARCHAR(25), @VALORPROP VARCHAR(10)
SELECT @MIN = MIN(ID), @MAX = MAX(ID) 
FROM @TABFILIAL

WHILE @MIN <= @MAX
BEGIN 
	/* LE OS VALORES LINHA A LINHA*/
	SELECT @FILIAL = FILIAL, @VALORPROP=VALORPROP
	FROM @TABFILIAL
	WHERE ID = @MIN

	IF EXISTS(SELECT 1 FROM PROP_FILIAIS WHERE FILIAL = @FILIAL AND PROPRIEDADE = '00116')
	BEGIN
		UPDATE PROP_FILIAIS 
		SET VALOR_PROPRIEDADE = @VALORPROP, DATA_PARA_TRANSFERENCIA=GETDATE()
		WHERE FILIAL = @FILIAL AND PROPRIEDADE = '00116'
	END
	ELSE
	BEGIN
		INSERT INTO PROP_FILIAIS VALUES ('00116',@FILIAL,1,@VALORPROP,GETDATE(),NULL)
	END
	SET @MIN = @MIN + 1
END

