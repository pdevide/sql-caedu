SELECT * FROM ESTOQUE_PROD1_ENT WHERE FILIAL = 'CD CAJAMAR' AND ROMANEIO_PRODUTO IN (
'T015519','T015521','T015522','T015523','T015524','T015526','T015527','T015528','T015529','T015530','T015531')


select ROMANEIO_PRODUTO, FILIAL, ESTOQUE_PROD1_ENT.PRODUTO, P.DESC_PRODUTO, ESTOQUE_PROD1_ENT.COR_PRODUTO, PC.DESC_COR_PRODUTO,
QTDE, EN_1, EN_2, EN_3, EN_4, EN_5, EN_6, EN_7, EN_8, EN_9, EN_10, EN_11, EN_12, EN_13, EN_14, EN_15, EN_16, CUSTO1 
FROM ESTOQUE_PROD1_ENT 
INNER JOIN PRODUTOS P ON P.PRODUTO = ESTOQUE_PROD1_ENT.PRODUTO
INNER JOIN PRODUTO_CORES PC ON PC.PRODUTO = ESTOQUE_PROD1_ENT.PRODUTO AND PC.COR_PRODUTO = ESTOQUE_PROD1_ENT.COR_PRODUTO
WHERE FILIAL = 'CD CAJAMAR' AND ROMANEIO_PRODUTO IN (
'T015519','T015521','T015522','T015523','T015524','T015526','T015527','T015528','T015529','T015530','T015531')
ORDER BY ROMANEIO_PRODUTO, ESTOQUE_PROD1_ENT.PRODUTO, ESTOQUE_PROD1_ENT.COR_PRODUTO

