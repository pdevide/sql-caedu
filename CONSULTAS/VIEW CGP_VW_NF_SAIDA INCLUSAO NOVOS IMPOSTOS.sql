 CREATE VIEW [dbo].[CGP_VW_NF_SAIDA] AS

 SELECT  EMITENTE.NOME_CLIFOR AS NOME_EMITENTE,  
         FAT.NF_SAIDA,  
         EMITENTE.CGC_CPF AS CNPJ_EMITENTE,  
		 FAT.SERIE_NF,  
		 FAT.EMISSAO AS EMISSAO,
		 CONVERT(VARCHAR(30),FAT.EMISSAO,3) AS FAT_EMISSAO,  
		 FAT.NATUREZA_SAIDA,  
		 CAST(FAT.PESO_BRUTO AS NUMERIC(15,2)) AS PESO_BRUTO,  
		 CAST(FAT.PESO_LIQUIDO AS NUMERIC(15,2)) AS PESO_LIQUIDO,  
		 EMITENTE.CLIFOR AS CODIGO_EMITENTE,  
		 SUM(FI.VALOR_ITEM) AS VALOR_ITEM ,
		 FAT.VALOR_TOTAL,  
		 EMITENTE.UF AS UF_EMITENTE,  
		 DESTINATARIO.UF AS UF_DESTINATARIO,  
		 DESTINATARIO.NOME_CLIFOR AS NOME_DESTINATARIO,  
		 DESTINATARIO.CGC_CPF as CNPJ_DESTINATARIO,  
		 DESTINATARIO.CLIFOR AS CODIGO_DESTINATARIO,  
		 DESTINATARIO.EBS_ID_CLIENTE,  
		 DESTINATARIO.EBS_ID_LOCAL_CLIENTE,  
		 FAT.FILIAL,  		 
		 REPLACE(CES.DESC_ESPECIE_SERIE, '-','') AS DESC_ESPECIE_SERIE,  
		 EMIT_ESTABELC.COD_FILIAL AS IND_FILIAL_EMITENTE,  
		 CLIE_ESTABELC.COD_FILIAL AS IND_FILIAL_CLIENTE, 
		 FAT.DATA_PARA_TRANSFERENCIA, 						
		 (SELECT T.CODIGO_FISCAL_OPERACAO 
		    FROM (SELECT TOP 1 COUNT(1) AS CFOP, FATTI.CODIGO_FISCAL_OPERACAO 
                     FROM FATURAMENTO FATT WITH (NOLOCK)
		                  INNER JOIN FATURAMENTO_ITEM FATTI 
		                          ON FATTI.NF_SAIDA = FATT.NF_SAIDA 
		                         AND FATTI.SERIE_NF = FATT.SERIE_NF 
		    					 AND FATTI.FILIAL   = FATT.FILIAL
     							 AND FAT.NF_SAIDA = FATT.NF_SAIDA 
								 AND FAT.SERIE_NF = FATT.SERIE_NF 
								 AND FAT.FILIAL   = FATT.FILIAL
								 AND FAT.EMISSAO  = FATT.EMISSAO									 								 
		GROUP BY FATTI.CODIGO_FISCAL_OPERACAO ORDER BY 1 DESC ) T) 	AS CODIGO_FISCAL_OPERACAO,					   
	    CASE WHEN FAT.STATUS_NFE IN ('5','6') THEN 'N'  
		     WHEN (SELECT TOP 1 STATUS_NFE FROM FATURAMENTO FAT WITH (NOLOCK)  JOIN CADASTRO_CLI_FOR AS EMIT WITH (NOLOCK)  ON FAT.NOME_CLIFOR = EMIT.NOME_CLIFOR WHERE EMIT.CGC_CPF NOT LIKE '4637772%') = 1 THEN 'N'  
		     WHEN FAT.STATUS_NFE = '49' THEN 'S'  
		     WHEN FAT.STATUS_NFE = '59' THEN 'I'  
		END AS STATUS_NFE,  
       CASE WHEN FAT.STATUS_NFE='5' THEN FAT.PROTOCOLO_AUTORIZACAO_NFE ELSE FAT.PROTOCOLO_CANCELAMENTO_NFE END AS NFE_PROTOCOLO,  
	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='5'),0) AS ALIQUOTA_PIS,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='5'),0) AS BASE_PIS,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='5'),0) AS VALOR_PIS,  
	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='6'),0) AS ALIQUOTA_COFINS,  
       ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='6'),0) AS BASE_COFINS,  
       ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='6'),0) AS VALOR_COFINS,  
       ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='1'),0) AS ALIQUOTA_ICMS,  
       ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='1'),0) AS BASE_ICMS,  
       ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='1'),0) AS VALOR_ICMS,  
	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='2'),0) AS ALIQUOTA_IPI,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='2'),0) AS BASE_IPI,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='2'),0) AS VALOR_IPI,  				             
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='12'),0) AS VALOR_ST,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='12'),0) AS BASE_ST,   				             
	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='12'),0) AS ALIQUOTA_ST,  				 	   
	   /* novos impostos ibs /cbs 
		--92	IBS-UF
		--93	CBS
		--94	IS
		--95	IBS_MUN
	   */
	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='92'),0) AS ALIQUOTA_IBS_UF,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='92'),0) AS BASE_IBS_UF,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='92'),0) AS VALOR_IBS_UF,  

	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='93'),0) AS ALIQUOTA_CBS,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='93'),0) AS BASE_CBS,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='93'),0) AS VALOR_CBS,  

	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='94'),0) AS ALIQUOTA_IS,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='94'),0) AS BASE_IS,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='94'),0) AS VALOR_IS,  

	   ISNULL((SELECT SUM(TAXA_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='95'),0) AS ALIQUOTA_IBS_MUN,  
	   ISNULL((SELECT SUM(BASE_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK)  WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='95'),0) AS BASE_IBS_MUN,  
	   ISNULL((SELECT SUM(VALOR_IMPOSTO) FROM FATURAMENTO_IMPOSTO WITH (NOLOCK) WHERE NF_SAIDA=FAT.NF_SAIDA AND SERIE_NF=FAT.SERIE_NF AND FILIAL=FAT.FILIAL AND ID_IMPOSTO='95'),0) AS VALOR_IBS_MUN,  

       FAT.CHAVE_NFE,
	   FAT.NOTA_COMPLEMENTAR, 
	   FAT.QTDE_TOTAL AS QTDE_ITENS
  FROM FATURAMENTO  AS FAT  WITH (NOLOCK) 
	   INNER JOIN CADASTRO_CLI_FOR AS EMITENTE WITH (NOLOCK)  ON FAT.FILIAL = EMITENTE.NOME_CLIFOR  
	   INNER JOIN CADASTRO_CLI_FOR AS DESTINATARIO WITH (NOLOCK)  ON FAT.NOME_CLIFOR = DESTINATARIO.NOME_CLIFOR  
	   INNER JOIN SERIES_NF SE WITH (NOLOCK)  ON SE.SERIE_NF = FAT.SERIE_NF  
	   INNER JOIN CTB_ESPECIE_SERIE AS CES WITH (NOLOCK) ON  CES.ESPECIE_SERIE = SE.ESPECIE_SERIE  
	   LEFT JOIN FATURAMENTO_ITEM FI WITH (NOLOCK) ON FI.NF_SAIDA =FAT.NF_SAIDA AND FI.SERIE_NF =FAT.SERIE_NF AND FI.FILIAL =FAT.FILIAL
	   LEFT JOIN FILIAIS EMIT_ESTABELC WITH (NOLOCK)  ON  EMITENTE.CLIFOR = EMIT_ESTABELC.COD_FILIAL  
	   LEFT JOIN FILIAIS CLIE_ESTABELC WITH (NOLOCK)  ON DESTINATARIO.CLIFOR = CLIE_ESTABELC.COD_FILIAL  				   
 WHERE FAT.STATUS_NFE in ('5','6','49','59') 
 GROUP BY EMITENTE.NOME_CLIFOR,  
		  FAT.NF_SAIDA,  
		  EMITENTE.CGC_CPF,  
          FAT.SERIE_NF,  
		  FAT.EMISSAO,  
          FAT.NATUREZA_SAIDA,  
		  FAT.PESO_BRUTO,  
	      FAT.PESO_LIQUIDO,  		  
          FAT.VALOR_TOTAL,  
          EMITENTE.UF,  
		  DESTINATARIO.UF,  
		  DESTINATARIO.NOME_CLIFOR,  
		  DESTINATARIO.CGC_CPF,  
		  DESTINATARIO.CLIFOR,  
		  DESTINATARIO.EBS_ID_CLIENTE,  
		  DESTINATARIO.EBS_ID_LOCAL_CLIENTE,  
		  FAT.FILIAL,  
		  CES.DESC_ESPECIE_SERIE,  
		  EMITENTE.CLIFOR,  
		  EMIT_ESTABELC.COD_FILIAL,  
		  CLIE_ESTABELC.COD_FILIAL,  
		  FAT.STATUS_NFE,  
		  FAT.PROTOCOLO_AUTORIZACAO_NFE,  
		  FAT.PROTOCOLO_CANCELAMENTO_NFE,  
		  FAT.CHAVE_NFE,
		  FAT.DATA_PARA_TRANSFERENCIA,
		  FAT.NOTA_COMPLEMENTAR,
		  FAT.QTDE_TOTAL






GO


