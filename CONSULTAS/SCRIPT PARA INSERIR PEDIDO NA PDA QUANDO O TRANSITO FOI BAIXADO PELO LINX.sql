SELECT
25 as CODIGO_CLIENTE,
'A1109598' as CODIGO_PEDIDO,
'T6027378' as PRODUTO,
lep.COR_PRODUTO as COR,
NULL as TAMANHO,
p.GRADE as GRADE,
lep.QTDE_ENTRADA as QUANTIDADE,
pp.preco1 as CUSTO,
NULL as DESCONTO,
(pp.preco1 * lep.QTDE_ENTRADA) as VALOR_TOTAL,
lep.QTDE_ENTRADA as QUANTIDADE_RECEBIMENTO,
1 as USUINC,
GETDATE() as DATINC,
678 as USUALT,
NULL as DATALT,
lep.QTDE_ENTRADA as QUANTIDADE_PEDIDO,
NULL as LOTE,
NULL as VALIDADE,
NULL as NUMERO_DE_SERIE,
NULL as CODIGO_PACK,
NULL as ITEM
from LOJA_ENTRADAS le
inner join LOJA_ENTRADAS_PRODUTO lep on lep.ROMANEIO_PRODUTO =le.ROMANEIO_PRODUTO and lep.FILIAL=le.FILIAL
inner join produtos p on p.PRODUTO = lep.PRODUTO
inner join produtos_precos pp on pp.CODIGO_TAB_PRECO='02' and pp.PRODUTO=lep.PRODUTO
where le.SERIE_NF_ENTRADA='010'
and le.romaneio_produto in ('A1020848','A1044638','A1080579')
