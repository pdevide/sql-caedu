select 
25 as CODIGO_CLIENTE,
le.ROMANEIO_PRODUTO as CODIGO_PEDIDO,
le.CHAVE_NFE as CHAVE_NFE,
le.NUMERO_NF_TRANSFERENCIA as NOTAFISCAL,
le.SERIE_NF_ENTRADA as SERIE,
le.EMISSAO as EMISSAO,
NULL as XML,
NULL as CODIGO_FORNECEDOR,
x.clifor as FORNECEDOR_ERP,
NULL as SEQUENCIA_NF_ERP,
1 as CODIGO_STATUS,
1 as USUINC,
getdate() as DATINC,
678 as USUALT,
NULL as DATALT,
'TI' as TIPO_PEDIDO,
NULL as CODIGO_FILIAL,
NULL as CODIGO_FILIAL_DIVERGENCIA,
NULL as CODIGO_FILIAL_AVARIA,
NULL as DATA_ENTREGA,
NULL as DATA_ENTREGA_LIMITE,
NULL as ID_MOVIMENTO,
NULL as ID_MOVIMENTO_ITEM,
NULL as ROMANEIO,
NULL as CAMPANHA,
NULL as CHECK_LIST_APROVACAO,
0 as MANUSEIO,
NULL as REFERENCIA_PEDIDO
from LOJA_ENTRADAS le
left join (
select fp.pedido,csm.NOME_CLIFOR, cf.CLIFOR, f.chave_nfe 
from faturamento f 
inner join faturamento_prod fp on fp.NF_SAIDA=f.NF_SAIDA and fp.SERIE_NF=f.SERIE_NF and fp.FILIAL=f.FILIAL
inner join CSM_TRANSITO_NOTAS csm on csm.PEDIDO_TRANSFERENCIA = fp.pedido
inner join CADASTRO_CLI_FOR cf on cf.NOME_CLIFOR=csm.NOME_CLIFOR
) x on x.CHAVE_NFE = le.CHAVE_NFE 
where SERIE_NF_ENTRADA='010'
and romaneio_produto in ('A1020848','A1044638','A1080579')


