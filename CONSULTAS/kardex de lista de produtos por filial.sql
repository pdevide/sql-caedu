;WITH Produtos AS
(
    SELECT V.PRODUTO, V.COR_PRODUTO
    FROM (VALUES
        ('12150428', '00065'),
        ('N2030579', '00252'),
        ('N3030541', '00075'),
        ('N4030319', '00007'),
        ('V2320002', '00201')
    ) AS V(PRODUTO, COR_PRODUTO)
)
SELECT
    C.*,
    PC.DESC_COR_PRODUTO
FROM Produtos AS P
CROSS APPLY FX_MONTA_CARDEX_PA(
    P.PRODUTO,
    P.COR_PRODUTO,
    'SAO BERNARDO',
    0
) AS C
INNER JOIN PRODUTO_CORES AS PC
    ON PC.PRODUTO = C.PRODUTO
   AND PC.COR_PRODUTO = C.COR_PRODUTO;