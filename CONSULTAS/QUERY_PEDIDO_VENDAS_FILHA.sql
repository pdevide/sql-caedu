(SELECT VENDAS.PEDIDO
FROM VENDAS
JOIN CLIENTES_ATACADO ON VENDAS.CLIENTE_ATACADO = CLIENTES_ATACADO.CLIENTE_ATACADO
LEFT  JOIN PRODUTOS_PERIODOS_ENTREGAS ON VENDAS.NUMERO_ENTREGA = PRODUTOS_PERIODOS_ENTREGAS.NUMERO_ENTREGA
AND VENDAS.PERIODO_PCP = PRODUTOS_PERIODOS_ENTREGAS.PERIODO_PCP
JOIN CADASTRO_CLI_FOR ON VENDAS.CLIENTE_ATACADO = CADASTRO_CLI_FOR.NOME_CLIFOR
JOIN FILIAIS ON VENDAS.FILIAL = FILIAIS.FILIAL
JOIN TABELAS_PRECO ON VENDAS.CODIGO_TAB_PRECO = TABELAS_PRECO.CODIGO_TAB_PRECO
JOIN COND_ATAC_PGTOS ON VENDAS.CONDICAO_PGTO = COND_ATAC_PGTOS.CONDICAO_PGTO
LEFT JOIN NATUREZAS_SAIDAS ON VENDAS.NATUREZA_SAIDA = NATUREZAS_SAIDAS.NATUREZA_SAIDA
LEFT JOIN CTB_LX_TIPO_OPERACAO ON NATUREZAS_SAIDAS.CTB_TIPO_OPERACAO = CTB_LX_TIPO_OPERACAO.CTB_TIPO_OPERACAO
LEFT JOIN FILIAIS FILIAL_CLI ON VENDAS.CLIENTE_ATACADO = FILIAL_CLI.FILIAL
LEFT JOIN BANCOS ON VENDAS.BANCO = BANCOS.BANCO
LEFT JOIN FORNECEDORES ON VENDAS.COD_LICENCIADO = FORNECEDORES.COD_FORNECEDOR
WHERE VENDAS.CLIENTE_ATACADO = 'MENDES RIGONATTI E CIA LT' )
