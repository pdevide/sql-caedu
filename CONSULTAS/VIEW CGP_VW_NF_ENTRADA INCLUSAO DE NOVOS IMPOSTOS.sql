CREATE OR ALTER VIEW [dbo].[CGP_VW_NF_ENTRADA] AS 

select 
nfe.NF_ENTRADA,
nfe.SERIE_NF,
nfe.CNPJ_DESTINATARIO,
nfe.CNPJ_EMITENTE,
nfe.CODIGO_EMITENTE,
nfe.CODIGO_DESTINATARIO,
nfe.EMISSAO,
nfe.NATUREZA,
nfe.RECEBIMENTO,
nfe.PESO_BRUTO,
nfe.PESO,
nfe.VALOR_TOTAL,
nfe.CONDICAO_PGTO,
nfe.EBS_ID_COND_PAGAMENTO,
nfe.VALOR_TOTAL_M,
nfe.VALOR_TOTAL_AJUSTE_M,
nfe.NOME_CLIFOR,
nfe.UF_DESTINO,
nfe.UF_EMITENTE,
nfe.CODIGO_FISCAL_OPERACAO,
nfe.CLIFOR_FORNEC,
nfe.FATURA,
nfe.EBS_ID_FORNECEDOR,
nfe.EBS_ID_LOCAL_FORNECEDOR,
nfe.DESC_NO_SHOW,
nfe.DATA_PARA_TRANSFERENCIA,
nfe.VL_BRUTO,
nfe.DESC_ESPECIE_SERIE,
nfe.IND_FILIAL_EMITENTE,
nfe.IND_FILIAL_CLIENTE,
nfe.CHAVE_NFE,
nfe.ENCARGO,
nfe.FILIAL,
nfe.DESCONTO,
nfe.CTB_LANCAMENTO,
nfe.STATUS_NFE,
nfe.NFE_PROTOCOLO,
nfe.ALIQUOTA_PIS,
nfe.BASE_PIS,
nfe.VALOR_PIS,
nfe.ALIQUOTA_COFINS,
nfe.BASE_COFINS,
nfe.VALOR_COFINS,
nfe.ALIQUOTA_ICMS,
nfe.BASE_ICMS,
nfe.VALOR_ICMS,
nfe.ALIQUOTA_IPI,
nfe.BASE_IPI,
nfe.VALOR_IPI,
nfe.BASE_ICMS_ST,
nfe.VALOR_ICMS_ST,
nfe.DATA_RECEBIMENTO,
nfe.CGC_CPF,
nfe.VL_BRUTO - (nfe.VALOR_ICMS + nfe.VALOR_COFINS + nfe.VALOR_IPI + nfe.VALOR_PIS) AS VALOR_LIQUIDO,
nfe.NOTA_COMPLEMENTAR,

nfe.ALIQUOTA_IBS_UF,
nfe.BASE_IBS_UF,
nfe.VALOR_IBS_UF,

nfe.ALIQUOTA_CBS,
nfe.BASE_CBS,
nfe.VALOR_CBS,

nfe.ALIQUOTA_IS,
nfe.BASE_IS,
nfe.VALOR_IS,

nfe.ALIQUOTA_IBS_MUN,
nfe.BASE_IBS_MUN,
nfe.VALOR_IBS_MUN,

nfe.QTDE_ITENS
FROM (
	SELECT ENT.NF_ENTRADA, 
		   ENT.SERIE_NF_ENTRADA AS SERIE_NF, 
	                   DEST.CGC_CPF AS CNPJ_DESTINATARIO, 
					   EMIT.CGC_CPF As CNPJ_EMITENTE, 
					   EMIT.CLIFOR AS CODIGO_EMITENTE, 
	                   DEST.CLIFOR AS CODIGO_DESTINATARIO, 
	                   ENT.EMISSAO,
					   ENT.NATUREZA, 
	                   ENT.RECEBIMENTO,
	                   ENT.PESO_BRUTO, 
	                   ENT.PESO, 
	                   Cast(ENT.VALOR_TOTAL as NUMERIC(15,2)) As VALOR_TOTAL, 
					   ENT.CONDICAO_PGTO,
					   CP.EBS_ID_COND_PAGAMENTO,
	                   CAST(SUM(EI.PRECO_UNITARIO * EI.QTDE_ITEM) AS NUMERIC(15,2)) AS VALOR_TOTAL_M, 
	                   CAST(SUM(EI.VALOR_DESCONTOS * -1) AS NUMERIC(15,2)) AS VALOR_TOTAL_AJUSTE_M, 
	                   ENT.NOME_CLIFOR, 
	                   DEST.UF AS UF_DESTINO, 
	                   EMIT.UF AS UF_EMITENTE, 	                   
	                   EMIT.CLIFOR AS CLIFOR_FORNEC, 
					   CAST(CAST(ENT.NF_ENTRADA AS NUMERIC)AS VARCHAR) + '-' + ENT.SERIE_NF_ENTRADA AS FATURA,
	                   EMIT.EBS_ID_FORNECEDOR, 
				   	   EMIT.EBS_ID_LOCAL_FORNECEDOR, 
					   CAST(CPM.DESCONTO_OBTIDO AS NUMERIC(15,2)) AS DESC_NO_SHOW ,
					   ENT.DATA_PARA_TRANSFERENCIA,					   
					  (SELECT T.CODIGO_FISCAL_OPERACAO 
					     FROM (SELECT TOP 1 COUNT(1) AS CFOP, ENTII.CODIGO_FISCAL_OPERACAO 
						         FROM ENTRADAS ENTT 
								      INNER JOIN  ENTRADAS_ITEM ENTII (nolock)  
									          ON ENTII.NF_ENTRADA=ENTT.NF_ENTRADA 
											 AND ENTII.SERIE_NF_ENTRADA=ENTT.SERIE_NF_ENTRADA 
											 AND ENTII.NOME_CLIFOR=ENTT.NOME_CLIFOR  

											 AND ENT.NF_ENTRADA  = ENTT.NF_ENTRADA
											 AND ENT.SERIE_NF_ENTRADA    = ENTT.SERIE_NF_ENTRADA
											 AND ENT.CHAVE_NFE   = ENTT.CHAVE_NFE
											 AND ENT.NOME_CLIFOR = ENTT.NOME_CLIFOR
											 AND ENT.RECEBIMENTO = ENTT.RECEBIMENTO
								 GROUP BY ENTII.CODIGO_FISCAL_OPERACAO ORDER BY 1 DESC ) T) AS CODIGO_FISCAL_OPERACAO,

					   CASE WHEN ENT.desconto IS NOT NULL THEN (SUM(ei.valor_item) - ENT.desconto) + ENT.encargo  ELSE SUM(ei.valor_item)  END AS VL_BRUTO,
					   REPLACE(CES.DESC_ESPECIE_SERIE, '-','') AS DESC_ESPECIE_SERIE, 
					   EMIT_ESTABELC.COD_FILIAL AS IND_FILIAL_EMITENTE, 
				       DEST_ESTABELC.COD_FILIAL AS IND_FILIAL_CLIENTE, 
				       ENT.CHAVE_NFE, 
					   ENT.ENCARGO As ENCARGO,
					   ENT.FILIAL AS FILIAL,
					   ENT.DESCONTO AS DESCONTO,
					   ENT.CTB_LANCAMENTO AS CTB_LANCAMENTO,
				       CASE WHEN ENT.STATUS_NFE = '5' THEN 'N' 
				       WHEN (SELECT TOP 1 STATUS_NFE FROM ENTRADAS ENT JOIN CADASTRO_CLI_FOR AS EMIT ON ENT.NOME_CLIFOR = EMIT.NOME_CLIFOR WHERE EMIT.CGC_CPF NOT LIKE '4637772%') = 1 THEN 'N' 
				       WHEN ENT.STATUS_NFE = '49' THEN 'S' 
				       WHEN ENT.STATUS_NFE = '59' THEN 'I' 
				       END AS STATUS_NFE, 
					   CASE WHEN ENT.STATUS_NFE='5' THEN Ent.PROTOCOLO_AUTORIZACAO_NFE ELSE ent.PROTOCOLO_CANCELAMENTO_NFE END AS NFE_PROTOCOLO, 
				       ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='5'),0) AS ALIQUOTA_PIS, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='5'),0) AS BASE_PIS, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='5'),0) AS VALOR_PIS, 
					   ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='6'),0) AS ALIQUOTA_COFINS, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='6'),0) AS BASE_COFINS, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='6'),0) AS VALOR_COFINS, 
					   ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='1'),0) AS ALIQUOTA_ICMS, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='1'),0) AS BASE_ICMS, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='1'),0) AS VALOR_ICMS, 
					   ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='2'),0) AS ALIQUOTA_IPI, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='2'),0) AS BASE_IPI, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='2'),0) AS VALOR_IPI, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='12'),0) AS BASE_ICMS_ST, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='12'),0) AS VALOR_ICMS_ST , 
						--92	IBS_UF
						--93	CBS
						--94	IS
						--95	IBS_MUN
				       ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='92'),0) AS ALIQUOTA_IBS_UF, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='92'),0) AS BASE_IBS_UF, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='92'),0) AS VALOR_IBS_UF, 

					   ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='93'),0) AS ALIQUOTA_CBS, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='93'),0) AS BASE_CBS, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='93'),0) AS VALOR_CBS, 

				       ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='94'),0) AS ALIQUOTA_IS, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='94'),0) AS BASE_IS, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='94'),0) AS VALOR_IS, 

					   ISNULL((SELECT SUM(case when TAXA_IMPOSTO = 0 then TAXA_IMPOSTO_ESPELHO ELSE TAXA_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='95'),0) AS ALIQUOTA_IBS_MUN, 
					   ISNULL((SELECT SUM(case when BASE_IMPOSTO = 0 then BASE_IMPOSTO_ESPELHO ELSE BASE_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='95'),0) AS BASE_IBS_MUN, 
					   ISNULL((SELECT SUM(case when VALOR_IMPOSTO = 0 then VALOR_IMPOSTO_ESPELHO ELSE VALOR_IMPOSTO END ) FROM ENTRADAS_IMPOSTO WHERE NF_ENTRADA=ENT.NF_ENTRADA AND SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND NOME_CLIFOR=ENT.NOME_CLIFOR AND ID_IMPOSTO='95'),0) AS VALOR_IBS_MUN, 

					   ENT.RECEBIMENTO AS DATA_RECEBIMENTO,
					   F.CGC_CPF,
					   ent.NOTA_COMPLEMENTAR, 
					   ENT.QTDE_TOTAL AS QTDE_ITENS
					   
				FROM ENTRADAS (nolock) AS ENT 
				JOIN CADASTRO_CLI_FOR (nolock) AS DEST ON ENT.FILIAL = DEST.NOME_CLIFOR /*DESTINATARIO*/ 
				JOIN CADASTRO_CLI_FOR (nolock) AS EMIT ON ENT.NOME_CLIFOR = EMIT.NOME_CLIFOR  /*EMITENTE*/ 
				JOIN CTB_ESPECIE_SERIE (nolock) AS CES ON ent.ESPECIE_SERIE = ces.ESPECIE_SERIE
				INNER JOIN COND_ENT_PGTOS (nolock) CP ON ENT.CONDICAO_PGTO = CP.CONDICAO_PGTO
				LEFT JOIN CTB_A_PAGAR_FATURA CPF ON CPF.FATURA = ENT.NF_ENTRADA AND CPF.LANCAMENTO = ENT.CTB_LANCAMENTO 
				LEFT JOIN CTB_A_PAGAR_MOV CPM ON CPF.LANCAMENTO = CPM.LANCAMENTO_MOV  
				LEFT JOIN ENTRADAS_ITEM EI (nolock) ON EI.NF_ENTRADA=ENT.NF_ENTRADA AND EI.SERIE_NF_ENTRADA=ENT.SERIE_NF_ENTRADA AND EI.NOME_CLIFOR=ENT.NOME_CLIFOR 
				LEFT JOIN PRODUTOS P (nolock) ON P.PRODUTO = EI.CODIGO_ITEM 
				LEFT JOIN FILIAIS EMIT_ESTABELC (nolock) ON EMIT_ESTABELC.COD_FILIAL = EMIT.COD_CLIFOR 
				LEFT JOIN FILIAIS DEST_ESTABELC (nolock) ON DEST_ESTABELC.COD_FILIAL = DEST.COD_CLIFOR 
				INNER JOIN filiais f WITH (NOLOCK) ON f.filial = ENT.filial  
				WHERE ENT.STATUS_NFE in ('1','5','49','59')
				GROUP BY ENT.NF_ENTRADA, 
					ENT.SERIE_NF_ENTRADA, 
					DEST.CGC_CPF, 
					EMIT.CGC_CPF, 
					DEST.CLIFOR, 
					ENT.EMISSAO, 
					ENT.NATUREZA, 
					ENT.RECEBIMENTO,  
					ENT.PESO_BRUTO, 
					ENT.PESO, 
					ENT.VALOR_TOTAL, 
					DEST.CLIFOR, 
					ENT.NOME_CLIFOR, 
					DEST.UF, 
					EMIT.UF, 					
					EMIT.CLIFOR, 
					EMIT.EBS_ID_FORNECEDOR, 
					EMIT.EBS_ID_LOCAL_FORNECEDOR, 
					CES.DESC_ESPECIE_SERIE, 
					EMIT_ESTABELC.COD_FILIAL, 
					DEST_ESTABELC.COD_FILIAL, 
					ENT.CHAVE_NFE, 
					ENT.STATUS_NFE, 
					ENT.PROTOCOLO_AUTORIZACAO_NFE, 
					ENT.PROTOCOLO_CANCELAMENTO_NFE,
					ENT.ENCARGO,
					ENT.FILIAL,
					ENT.DESCONTO,
					ENT.CTB_LANCAMENTO,
					CPM.DESCONTO_OBTIDO,
					ENT.CONDICAO_PGTO,
					CP.EBS_ID_COND_PAGAMENTO,
					ENT.DATA_PARA_TRANSFERENCIA,
					F.CGC_CPF,
					ent.NOTA_COMPLEMENTAR,
					ENT.QTDE_TOTAL
		) nfe
					






GO


