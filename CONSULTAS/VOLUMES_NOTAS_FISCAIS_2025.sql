;WITH ITENS AS (
    SELECT NF_SAIDA, SERIE_NF, FILIAL, COUNT(*) AS QTDE_ITENS
    FROM FATURAMENTO_PROD
    GROUP BY NF_SAIDA, SERIE_NF, FILIAL
),
NF AS (
    SELECT
        CAST(F.EMISSAO AS date) AS EMISSAO,
        F.NOME_CLIFOR,
        ISNULL(I.QTDE_ITENS, 0) AS QTDE_ITENS
    FROM FATURAMENTO F
    LEFT JOIN ITENS I
           ON I.NF_SAIDA = F.NF_SAIDA
          AND I.SERIE_NF = F.SERIE_NF
          AND I.FILIAL   = F.FILIAL
    WHERE F.NATUREZA_SAIDA = '120.01'
      AND F.STATUS_NFE = 5
      AND F.EMISSAO >= '20251001'
      AND F.EMISSAO <  '20260101'
),
DIA AS (
    SELECT
        EMISSAO,
        COUNT(DISTINCT NOME_CLIFOR) AS QTD_LOJAS,
        COUNT(*)                    AS QTD_NOTAS,
        SUM(QTDE_ITENS)             AS QTDE_ITENS
    FROM NF
    GROUP BY EMISSAO
)
SELECT
    FORMAT(EMISSAO, 'dd/MM/yyyy') AS DATA_FATUR,
    QTD_LOJAS,
    QTD_NOTAS,
    QTDE_ITENS,
    CAST(ROUND(QTDE_ITENS * 1.0 / NULLIF(QTD_NOTAS, 0), 0) AS int) AS MEDIA_ITENS_POR_NOTA
FROM DIA
ORDER BY EMISSAO;