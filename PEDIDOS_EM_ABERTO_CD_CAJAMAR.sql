select	c.pedido, 
		c.fornecedor, 
		c.filial_a_entregar, 
		c.filial_cobranca, 
		c.filial_a_faturar,
		CAST(C.TOT_QTDE_ORIGINAL AS INT) TOT_QTDE_ORIGINAL,
		CAST(C.TOT_QTDE_ENTREGAR AS INT) TOT_QTDE_ENTREGAR,
		P.ENTREGA, 
		P.LIMITE_ENTREGA
from compras c 
INNER JOIN (SELECT DISTINCT PEDIDO, ENTREGA, LIMITE_ENTREGA 
			FROM COMPRAS_PRODUTO CP ) P 
	ON P.PEDIDO = C.PEDIDO
where c.TOT_QTDE_ENTREGAR>0 
AND c.FILIAL_A_ENTREGAR='CD REGIS'
AND c.pedido not in 
(select pedido from COMPRAS_PROD_CANCELADA)
AND P.LIMITE_ENTREGA > '20190112'
ORDER BY P.LIMITE_ENTREGA ASC


