FROM PRODUTOS P
INNER JOIN PRODUTOS_PRECOS PP00 ON PP00.PRODUTO = P.PRODUTO AND PP00.CODIGO_TAB_PRECO = '00'
INNER JOIN PRODUTOS_PRECOS PP01 ON PP01.PRODUTO = P.PRODUTO AND PP01.CODIGO_TAB_PRECO = '01'
