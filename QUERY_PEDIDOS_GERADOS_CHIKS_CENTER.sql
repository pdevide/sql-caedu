       COMPRAS.TOT_QTDE_ORIGINAL, 
       COMPRAS.TOT_QTDE_ENTREGAR, 
       COMPRAS.TOT_VALOR_ORIGINAL, 
       COMPRAS.TOT_VALOR_ENTREGAR, 
       COMPRAS.TIPO_COMPRA, 
       COMPRAS.STATUS_APROVACAO, 
       COMPRAS.STATUS_COMPRA, 
       COMPRAS.ERP_PACK_RESTO, 
       COMPRAS_PRODUTO.PRODUTO, 
       COMPRAS_PRODUTO.ENTREGA, 
       COMPRAS_PRODUTO.COR_PRODUTO, 
       PRODUTO_CORES.DESC_COR_PRODUTO, 
       COMPRAS_PRODUTO.LIMITE_ENTREGA, 
       COMPRAS_PRODUTO.CUSTO1, 
       COMPRAS_PRODUTO.QTDE_ORIGINAL, 
       COMPRAS_PRODUTO.QTDE_CANCELADA, 
       COMPRAS_PRODUTO.QTDE_ENTREGUE, 
       COMPRAS_PRODUTO.QTDE_ENTREGAR, 
       COMPRAS_PRODUTO.VALOR_ORIGINAL, 
       COMPRAS_PRODUTO.VALOR_ENTREGUE, 
       COMPRAS_PRODUTO.VALOR_ENTREGAR, 
       COMPRAS_PRODUTO.PACKS, 
       COMPRAS_PRODUTO.CO1, 
       COMPRAS_PRODUTO.CO2, 
       COMPRAS_PRODUTO.CE1, 
       COMPRAS_PRODUTO.CE2, 
       COMPRAS_PRODUTO.QTDE, 
       CAEDU_COMPRAS_PRODUTOS_PACKS.QTDE       AS QTDE_PACK, 
       CAEDU_COMPRAS_PRODUTOS_PACKS.Q1, 
       CAEDU_COMPRAS_PRODUTOS_PACKS.Q2, 
       CAEDU_COMPRAS_PRODUTOS_PACKS_TOTAL.QTDE AS QTDE_PACK_TOTAL, 
       CAEDU_COMPRAS_PRODUTOS_PACKS_TOTAL.Q1   AS Q1_PACK_TOTAL, 
