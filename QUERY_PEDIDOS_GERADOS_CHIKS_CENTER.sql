       PRODUTOS_PACKS_PERMITIDOS.Q1            AS Q1_PACK_PERMITIDO, 
       PRODUTOS_PACKS_PERMITIDOS.Q2            AS Q2_PACK_PERMITIDO 
FROM   COMPRAS 
       INNER JOIN COMPRAS_PRODUTO 
               ON COMPRAS.PEDIDO = COMPRAS_PRODUTO.PEDIDO 
       INNER JOIN CAEDU_COMPRAS_PRODUTOS_PACKS 
               ON COMPRAS.PEDIDO = CAEDU_COMPRAS_PRODUTOS_PACKS.PEDIDO 
       INNER JOIN CAEDU_COMPRAS_PRODUTOS_PACKS_TOTAL 
               ON COMPRAS.PEDIDO = 
                  CAEDU_COMPRAS_PRODUTOS_PACKS_TOTAL.PEDIDO 
       INNER JOIN PRODUTOS 
               ON COMPRAS_PRODUTO.PRODUTO = PRODUTOS.PRODUTO 
       INNER JOIN PRODUTO_CORES 
               ON COMPRAS_PRODUTO.PRODUTO = PRODUTO_CORES.PRODUTO 
                  AND COMPRAS_PRODUTO.COR_PRODUTO = 
                      PRODUTO_CORES.COR_PRODUTO 
                  AND PRODUTOS.PRODUTO = PRODUTO_CORES.PRODUTO 
       INNER JOIN PRODUTOS_BARRA 
               ON PRODUTO_CORES.PRODUTO = PRODUTOS_BARRA.PRODUTO 
                  AND PRODUTO_CORES.COR_PRODUTO = 
                      PRODUTOS_BARRA.COR_PRODUTO 
       INNER JOIN PRODUTOS_PACKS_PERMITIDOS 
               ON PRODUTOS.PRODUTO = PRODUTOS_PACKS_PERMITIDOS.PRODUTO 
WHERE COMPRAS.EMISSAO = '20190603' AND COMPRAS.FORNECEDOR = 'CHIK S CENTER MODAS LTDA'

