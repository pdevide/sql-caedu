ALTER VIEW [dbo].[CGP_VW_UNIDADES] AS 

SELECT RTRIM(LTRIM(A.FILIAL)) AS FILIAL
      ,RTRIM(LTRIM(A.COD_FILIAL)) AS COD_FILIAL
      ,CASE 
		WHEN A.FILIAL LIKE 'POS%' THEN RIGHT(A.COD_FILIAL,4)
		ELSE 	substring(RTRIM(LTRIM(A.CGC_CPF)), 9,4) 
		END as COD_LOJA
	  ,RTRIM(LTRIM(A.DATA_ABERTURA)) AS DATA_ABERTURA 
	  ,RTRIM(LTRIM(A.EMPRESA)) AS EMPRESA
	  ,RTRIM(LTRIM(A.CGC_CPF)) AS CGC_CPF
	  ,COALESCE(RTRIM(LTRIM(B.IP)),'0.0.0.0') AS IP
	  --,COALESCE(RTRIM(LTRIM(B.ATIVO)),'1') AS ATIVO
	  ,A.ERP_ENVIAR_ALOCACAO_UNOUS AS ATIVO 
	  ,RTRIM(LTRIM(C.BAIRRO)) AS BAIRRO
	  ,RTRIM(LTRIM(C.CEP)) AS CEP
	  ,RTRIM(LTRIM(C.ENDERECO)) AS ENDERECO
	  ,RTRIM(LTRIM(C.RG_IE)) AS RG_IE
	  ,RTRIM(LTRIM(C.DDI)) AS DDI
	  ,RTRIM(LTRIM(C.DDD1)) AS DDD1
	  ,RTRIM(LTRIM(C.TELEFONE1)) AS TELEFONE1
	  ,RTRIM(LTRIM(C.RAMAL1)) AS RAMAL1
	  ,RTRIM(LTRIM(C.DDD2)) AS DDD2
	  ,RTRIM(LTRIM(C.TELEFONE2)) AS TELEFONE2
	  ,RTRIM(LTRIM(C.RAMAL2)) AS RAMAL2 
	  ,ISNULL(PLV.PROPRIEDADE,'00000') AS PROPRIEDADE
	  ,CASE WHEN PLV.VALOR_PROPRIEDADE IS NOT NULL THEN  PLV.VALOR_PROPRIEDADE
	        WHEN C.NOME_CLIFOR LIKE 'CD %' THEN 'CD'
	        ELSE 'R1'END AS COD_REGIONAL
	  ,SUBSTRING(RTRIM(LTRIM(A.CGC_CPF)), 9,4) AS COD_RETAGUARDA
	  ,A.REGIAO AS REGION
	  ,A.DATA_PARA_TRANSFERENCIA
	  ,CASE WHEN C.NOME_CLIFOR LIKE 'CD %' THEN 'CD' ELSE 'LOJA FISICA' END TIPO
	  ,RTRIM(LTRIM(C.NUMERO)) AS NUMERO
	  ,RTRIM(LTRIM(C.CIDADE)) AS CIDADE
	  ,RTRIM(LTRIM(C.COMPLEMENTO)) AS COMPLEMENTO
	  ,RTRIM(LTRIM(C.UF)) AS UF
	  ,C.COD_MUNICIPIO_IBGE As COD_CIDADE
	  ,RTRIM(LTRIM(ISNULL(A.ERP_UNOUS_CLUSTER_ABC, 'E'))) AS CURVA
 FROM  DBO.FILIAIS A   
      LEFT JOIN   DBO.INFO_LOJAS B 
	         ON B.CODIGO_FILIAL = A.COD_FILIAL 
			--AND B.ATIVO = 1  
	 INNER JOIN DBO.CADASTRO_CLI_FOR C 
	         ON C.COD_CLIFOR = A.COD_FILIAL 
     LEFT JOIN DBO.PROP_LOJAS_VAREJO PLV WITH (NOLOCK)
	         ON PLV.CODIGO_FILIAL = A.COD_FILIAL
			AND PROPRIEDADE = '00021'
WHERE 1 = 1   
  AND A.EMPRESA = 1
  AND A.MATRIZ = 'MATRIZ'  
  AND (RTRIM(LTRIM(A.CGC_CPF)) <> '46377727000193' OR  A.FILIAL LIKE 'POS%')
  AND A.COD_FILIAL NOT IN ('000090','000091','000066','000089','000002','000051','000040','000038','000109','000037','000069','000067','000033','000024','000045','000022','000085','000034','000064','000013','000054','999999','000070','000072','000093','000095','000016','000043','000073','000096','000017','000106','000094','000078','000052','000049','000044','000021','000110', '000112','000115');



