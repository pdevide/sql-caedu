declare @min int, @max int, @pedido varchar(12), @total_antes numeric(14,2), @total_depois numeric(14,2)
select @min=min(id), @max=max(id) from @tabpedido
select @min as min, @max as max

while @min <= @max
begin
	select @pedido = pedido 
	from @tabpedido where id = @min
	
	if exists(select 1 from compras where desconto <> 0 and pedido = @pedido)
	begin
		
		select @total_antes = TOT_VALOR_ORIGINAL, @total_depois = (TOT_VALOR_ORIGINAL + desconto)
		from compras 
		where pedido = @pedido
		
		update @tabpedido set total_antes = @total_antes, total_depois=@total_depois 
		where id = @min

		update compras set  TOT_VALOR_ORIGINAL = (TOT_VALOR_ORIGINAL + desconto), desconto = 0 WHERE PEDIDO = @pedido
	end
	set @min = @min + 1
end
