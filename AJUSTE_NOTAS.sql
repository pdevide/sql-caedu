UPDATE FATURAMENTO SET 
NATUREZA_SAIDA = '120.01' ,
TIPO_FATURAMENTO = 'TRANSFERENCIA'            
where FILIAL='CD REGIS' AND 
NF_SAIDA IN ('0074231','0074250','0074394','0074394','0074396')

UPDATE FATURAMENTO_PROD
SET 
CODIGO_FISCAL_OPERACAO = CASE CODIGO_FISCAL_OPERACAO
							 WHEN '5102' THEN '5152'
							 WHEN '5403' THEN '5409'
							 --WHEN '1409' THEN '5409'
						ELSE CODIGO_FISCAL_OPERACAO
						END

where FILIAL='CD REGIS' AND 
NF_SAIDA IN ('0074231','0074250','0074394','0074394','0074396')

UPDATE FATURAMENTO_ITEM
SET 
CODIGO_FISCAL_OPERACAO = CASE CODIGO_FISCAL_OPERACAO
							 WHEN '5102' THEN '5152'
							 WHEN '5403' THEN '5409'
							 --WHEN '1409' THEN '5409'
						ELSE CODIGO_FISCAL_OPERACAO
						END,
CONTA_CONTABIL='114.01.005'
where FILIAL='CD REGIS' AND 
NF_SAIDA IN ('0074231','0074250','0074394','0074394','0074396')


UPDATE FATURAMENTO_IMPOSTO
SET BASE_IMPOSTO=0, TAXA_IMPOSTO=0, VALOR_IMPOSTO=0
WHERE FILIAL='CD REGIS'  AND ID_IMPOSTO IN (5,6) AND
NF_SAIDA IN ('0074231','0074250','0074394','0074394','0074396')





