WITH SEMBOX (FILIAL,LOJADESTINO,CAIXA,DOCA,CODIGO_FILIAL,DATA, FATURADO, PRODUTO, COR_PRODUTO)
AS
(
SELECT F.FILIAL, F.FILIAL AS LOJADESTINO,A.CAIXA,A.DOCA,A.CODIGO_FILIAL,A.DATA, CAST(0 AS BIT) AS FATURADO, VE.PRODUTO, VE.COR_PRODUTO
FROM PDA_WMS_TB_EMBARQUE A
INNER JOIN FILIAIS F ON F.COD_FILIAL=A.CODIGO_FILIAL
LEFT JOIN FATURAMENTO_PROD FP ON FP.CAIXA=A.CAIXA
LEFT JOIN VENDAS_PROD_EMBALADO VE ON VE.CAIXA=A.CAIXA
WHERE 1=1
AND FP.CAIXA IS NULL AND VE.CAIXA IS not NULL
AND A.DATA>'20250101' AND A.DATA < CONVERT(varchar,GETDATE(),112)
)
select * 
--INTO [CCP\PAULO.DEVIDE].TB_CAIXAS_A_FATURAR_20250514
from sembox



