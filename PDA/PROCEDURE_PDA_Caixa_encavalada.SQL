ALTER PROCEDURE [dbo].[PDA_WMS_SP_IN_EMBARQUE]
@CAIXA	CHAR(8),		
@DOCA	varchar(100),		
@CODIGO_FILIAL  CHAR(15), 
@USUARIO	INT,
@CODIGO_TRANSPORTADORA char(5) =''	,
@PLACA VARCHAR(10)=''	,
@LACRE VARCHAR(20)=''	,
@COD_TIPO_VEICULO INT=0,
@CODIGO_ROTA VARCHAR(12)=''	
			
AS
BEGIN
IF(SELECT COUNT(*) FROM PDA_WMS_TB_EMBARQUE WHERE CAIXA=@CAIXA) =0
	BEGIN
			INSERT INTO PDA_WMS_TB_EMBARQUE
			(
					CAIXA			
				,DOCA			
				,CODIGO_FILIAL   
				,USUARIO
				,CODIGO_TRANSPORTADORA
				,PLACA
				,LACRE
				,COD_TIPO_VEICULO 
				,CODIGO_ROTA
			)
			VALUES
			(
					@CAIXA			
				,@DOCA			
				,@CODIGO_FILIAL   
				,@USUARIO
				,@CODIGO_TRANSPORTADORA
				,@PLACA
				,@LACRE
				,@COD_TIPO_VEICULO 
				,@CODIGO_ROTA
			)
	END
END
GO