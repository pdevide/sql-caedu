CREATE TRIGGER [dbo].[PDA_WMS_TRG_IN_STATUS]
   ON  [dbo].[PDA_WMS_TB_DISTRIBUICAO]
   AFTER  INSERT
AS 
BEGIN
	
	DECLARE @DISTRIBUICAO VARCHAR(12)
	
	 Select @DISTRIBUICAO = DISTRIBUICAO  From INSERTED;  

	IF(SELECT COUNT(*) FROM PDA_WMS_STATUS_DISTRIBUICAO WHERE DISTRIBUICAO=@DISTRIBUICAO)=0
	INSERT INTO PDA_WMS_STATUS_DISTRIBUICAO (DISTRIBUICAO,STATUS) VALUES(@DISTRIBUICAO,1)
	

END