CREATE PROCEDURE [dbo].[PDA_WMS_SP_IN_ARMAZENAGEM_PALETE] 
    @PALETE VARCHAR(20),
	@PACK CHAR(1)='N',
	@PRODUTO CHAR(12),
	@QUANTIDADE INT,
	@USUARIO INT,
	@VOLUME INT,
	@PEDIDO CHAR(8)

AS
BEGIN


INSERT INTO PDA_WMS_LOG_MOTAGEM_PALETE
	(
		
		 PALETE
		,PACK
		,PRODUTO
		,QUANTIDADE
		,USUARIO
		,VOLUME
		,PEDIDO
	)
	VALUES
	(
		 @PALETE
		,@PACK
		,@PRODUTO
		,@QUANTIDADE
		,@USUARIO
		,@VOLUME
		,@PEDIDO
	)


IF(SELECT COUNT(*) FROM PDA_WMS_TB_ARMAZENAGEM_PALETE WHERE PALETE=@PALETE AND PACK=@PACK AND PRODUTO = @PRODUTO) =0
