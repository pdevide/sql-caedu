CREATE  PROCEDURE [dbo].[PDA_WMS_SP_IN_DISTRIBUICAO_COLETA]          
   @DISTRIBUICAO   VARCHAR(12)='108528'                   
  ,@PRODUTO  VARCHAR(12)  ='VI02872'  
  ,@QTDE   INT    =1       
  ,@CAIXA   VARCHAR(25)  ='C0011907'            
  ,@TIMESTAMP      INT =44449997         
  ,@USUARIO     INT  =12           
  ,@ID_ENDERECO     INT  =13443
AS          
BEGIN     
    
    
    
    
 IF(SELECT COUNT(QTDE) FROM  PDA_WMS_TB_DISTRIBUICAO_COLETA WHERE DISTRIBUICAO = @DISTRIBUICAO AND TIMESTAMP = @TIMESTAMP AND CAIXA= @CAIXA) = 0     
    BEGIN                             
      IF (@QTDE > 0)  
      BEGIN  
        
       INSERT INTO PDA_WMS_TB_DISTRIBUICAO_COLETA          
           (  
		      DISTRIBUICAO          
			 ,ID_ENDERECO          
			 ,PRODUTO 
			 ,USUARIO          
			 ,QTDE               
			 ,CAIXA          
			 ,[TIMESTAMP]          
            )          
        VALUES          
           (          
			  @DISTRIBUICAO          
			 ,@ID_ENDERECO           
			 ,@PRODUTO 
			 ,@USUARIO                      
			 ,@QTDE          
			 ,@CAIXA          
			 ,@TIMESTAMP          
           )      
                 
   END  

              
          --ATUALIZANDO O ESTOQUE DO PALETE
              
          DECLARE @PALETE VARCHAR(MAX)    
			 SET @PALETE = (SELECT TOP 1 PALETE FROM (SELECT      AP.PALETE,ID_ENDERECO   FROM  PDA_WMS_TB_ARMAZENAGEM E 
																   INNER JOIN PDA_WMS_TB_ARMAZENAGEM_PALETE AP ON AP.PALETE = E.PALETE
																   GROUP BY ID_ENDERECO,AP.PALETE)AP WHERE ID_ENDERECO = @ID_ENDERECO)     
			 IF @PALETE <> ''    
			 BEGIN              
					UPDATE PDA_WMS_TB_ARMAZENAGEM_PALETE SET QUANTIDADE=QUANTIDADE-@QTDE WHERE PALETE=@PALETE AND PRODUTO=@PRODUTO   
        
					IF(SELECT sum(QUANTIDADE) FROM PDA_WMS_TB_ARMAZENAGEM_PALETE WHERE PALETE=@PALETE AND PRODUTO = @PRODUTO) <=0    
					BEGIN    
					 DELETE  PDA_WMS_TB_ARMAZENAGEM_PALETE WHERE PALETE=@PALETE AND PRODUTO = @PRODUTO    
					END    
        
					IF (SELECT COUNT(*) FROM PDA_WMS_TB_ARMAZENAGEM_PALETE WHERE PALETE=@PALETE) = 0    
					BEGIN    
					 DELETE FROM PDA_WMS_TB_ARMAZENAGEM WHERE PALETE=@PALETE AND ID_ENDERECO = @ID_ENDERECO    
					END    
        
             END
              
     
END 
END   

