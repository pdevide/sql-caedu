	E5.base_imposto_calc AS PIS_BASE_IMPOSTO_CALC, 
	E5.taxa_imposto AS PIS_TAXA_IMPOSTO, 
	E6.valor_imposto AS COFINS_VALOR_IMPOSTO, 
	E6.base_imposto AS COFINS_BASE_IMPOSTO, 
	E6.base_imposto_calc AS COFINS_BASE_IMPOSTO_CALC, 
	E6.taxa_imposto AS COFINS_TAXA_IMPOSTO 

from compras c 

inner join 
	compras_produto cp on cp.pedido = c.pedido

inner join 
	produtos p on p.produto = cp.produto

left join 
	estoque_prod_ent stk on stk.pedido = c.pedido

left join 
	entradas e 
		on e.NF_ENTRADA = stk.NF_ENTRADA and e.SERIE_NF_ENTRADA = stk.SERIE_NF_ENTRADA and e.NOME_CLIFOR = stk.NOME_CLIFOR

--NF_ENTRADA, SERIE_NF_ENTRADA, ITEM_IMPRESSAO, SUB_ITEM_TAMANHO, NOME_CLIFOR
left join ENTRADAS_ITEM ei on ei.NF_ENTRADA=stk.NF_ENTRADA and ei.SERIE_NF_ENTRADA=stk.SERIE_NF_ENTRADA
			and ei.NOME_CLIFOR = stk.NOME_CLIFOR and ei.CODIGO_ITEM = cp.PRODUTO 

LEFT JOIN   ENTRADAS_IMPOSTO E1 /*ICMS*/
		ON E1.ID_IMPOSTO=1 AND E1.NF_ENTRADA=stk.NF_ENTRADA 
		AND E1.ITEM_IMPRESSAO = EI.ITEM_IMPRESSAO AND E1.NOME_CLIFOR = STK.NOME_CLIFOR

LEFT JOIN   ENTRADAS_IMPOSTO E2  /*IPI*/
		ON E2.ID_IMPOSTO=2 AND E2.NF_ENTRADA=stk.NF_ENTRADA 
		AND E2.ITEM_IMPRESSAO = EI.ITEM_IMPRESSAO AND E2.NOME_CLIFOR = STK.NOME_CLIFOR

LEFT JOIN   ENTRADAS_IMPOSTO E5  /*PIS*/
		ON E5.ID_IMPOSTO=5 AND E5.NF_ENTRADA=stk.NF_ENTRADA 
		AND E5.ITEM_IMPRESSAO = EI.ITEM_IMPRESSAO AND E5.NOME_CLIFOR = STK.NOME_CLIFOR

LEFT JOIN   ENTRADAS_IMPOSTO E6  /*COFINS*/
		ON E6.ID_IMPOSTO=6 AND E6.NF_ENTRADA=stk.NF_ENTRADA 
		AND E6.ITEM_IMPRESSAO = EI.ITEM_IMPRESSAO AND E6.NOME_CLIFOR = STK.NOME_CLIFOR

