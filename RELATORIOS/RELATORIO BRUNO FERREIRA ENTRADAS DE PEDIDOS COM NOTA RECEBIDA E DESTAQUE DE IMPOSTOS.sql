	E.VALOR_TOTAL AS VALOR_TOTAL_NF,
    EI.item_impressao, 
	E1.valor_imposto AS ICMS_VALOR_IMPOSTO, 
	E1.base_imposto AS ICMS_BASE_IMPOSTO, 
	E1.base_imposto_calc AS ICMS_BASE_IMPOSTO_CALC, 
	E1.taxa_imposto AS ICMS_TAXA_IMPOSTO, 
