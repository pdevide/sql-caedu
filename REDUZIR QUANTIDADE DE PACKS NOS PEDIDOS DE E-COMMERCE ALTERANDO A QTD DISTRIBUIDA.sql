DECLARE @PEDIDO VARCHAR(10), @PRODUTO VARCHAR(12), @FATOR INT

WHILE @I<=@TOT
BEGIN
	
	PRINT @I

	SELECT @PEDIDO=PEDIDO, @PRODUTO = PRODUTO, @FATOR=FATOR
	FROM @tabped WHERE ID=@I
	
	
	update cp 
	set		QTDE_ORIGINAL = (ppp.qtde * @FATOR),
			QTDE_ENTREGAR = (ppp.QTDE * @FATOR),
			VALOR_ORIGINAL = (ppp.QTDE * @FATOR)*CUSTO1, 
			VALOR_ENTREGAR=(ppp.QTDE * @FATOR)*CUSTO1, 
			ERP_VERBAS_EMPENHO=(ppp.QTDE * @FATOR)*CUSTO1,
			CO1=ISNULL(Q1,0)*@FATOR, CO2=ISNULL(q2,0)*@FATOR, CO3=ISNULL(q3,0)*@FATOR, CO4=ISNULL(q4,0)*@FATOR, 
			CO5=ISNULL(q5,0)*@FATOR, CO6=ISNULL(q6,0)*@FATOR, CO7=ISNULL(q7,0)*@FATOR, CO8=ISNULL(q8,0)*@FATOR, 
			CO9=ISNULL(q9,0)*@FATOR, CO10=ISNULL(q10,0)*@FATOR, CO11=ISNULL(q11,0)*@FATOR, CO12=ISNULL(q12,0)*@FATOR, 
			CO13=ISNULL(q13,0)*@FATOR, CO14=ISNULL(q14,0)*@FATOR, CO15=ISNULL(q15,0)*@FATOR, CO16=ISNULL(q16,0)*@FATOR
	from compras_produto cp 
	inner join produtos_packs_permitidos ppp on ppp.produto=cp.PRODUTO
				and ppp.COR_PRODUTO=cp.COR_PRODUTO and ppp.PACK = cp.PACKS
	where cp.pedido = @PEDIDO and cp.produto = @PRODUTO

	update compras 
	set TOT_QTDE_ORIGINAL = (select sum(qtde_original) from compras_produto where pedido=@PEDIDO),
		TOT_QTDE_ENTREGAR = (select sum(qtde_original) from compras_produto where pedido=@PEDIDO),
		TOT_VALOR_ORIGINAL= (select sum(qtde_original*CUSTO1) from compras_produto where pedido=@PEDIDO), 
		TOT_VALOR_ENTREGAR = (select sum(qtde_original*CUSTO1) from compras_produto where pedido=@PEDIDO)
	WHERE PEDIDO = @PEDIDO;
	-- acrescentar o ajuste de caixas aqui
	update c set erp_total_caixas_original = @FATOR, ERP_TOTAL_QTD_DISTRIB=@FATOR
	from compras c where pedido = @PEDIDO

	SET @I=@I + 1
END
