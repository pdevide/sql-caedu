CREATE TABLE DBO.CGP_LOG_ALTERACAO_PEDIDO (
    ID             INT IDENTITY PRIMARY KEY,
    PEDIDO         CHAR(8)  NOT NULL,
    CAMPO          VARCHAR(100)  NOT NULL,
    VALOR_ANTERIOR VARCHAR(200),
    VALOR_NOVO     VARCHAR(200),
    USUARIO        VARCHAR(100)  NOT NULL,
    DATA_HORA      DATETIME  DEFAULT GETDATE(),
    ARQUIVO_ORIGEM VARCHAR(200)
)

go

-- Índice para consultar alterações de um determinado PEDIDO
CREATE NONCLUSTERED INDEX IX_CGP_LOG_ALTERACAO_PEDIDO_PEDIDO_DATA
ON DBO.CGP_LOG_ALTERACAO_PEDIDO (PEDIDO ASC, DATA_HORA DESC)
INCLUDE (CAMPO, VALOR_ANTERIOR, VALOR_NOVO, USUARIO, ARQUIVO_ORIGEM);
go

-- Índice para filtros de auditoria por DATA_HORA
CREATE NONCLUSTERED INDEX IX_CGP_LOG_ALTERACAO_PEDIDO_DATA_HORA
ON DBO.CGP_LOG_ALTERACAO_PEDIDO (DATA_HORA ASC)
INCLUDE (PEDIDO, CAMPO, USUARIO);
go

-- Índice opcional para buscas por USUARIO
CREATE NONCLUSTERED INDEX IX_CGP_LOG_ALTERACAO_PEDIDO_USUARIO_DATA
ON DBO.CGP_LOG_ALTERACAO_PEDIDO (USUARIO ASC, DATA_HORA DESC)
INCLUDE (PEDIDO, CAMPO);
go

