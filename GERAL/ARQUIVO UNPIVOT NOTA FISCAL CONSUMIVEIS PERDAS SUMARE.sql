SELECT cast(0 as int) as arquivo, unp.PRODUTO, unp.COR_PRODUTO,ISNULL(CODIGO_BARRA,'') AS CODIGO_BARRA, unp.DESC_PRODUTO, UNP.DESC_COR_PRODUTO,
/*CAST(SUBSTRING(POSICAO,2,2) AS INT) AS TAMANHO, */
 /*ISNULL(B.GRADE,'') AS GRADE*/
 ABS(QTD) AS QTD, UNP.PRECO1
FROM (
select ESTOQUE_PROD_CTG_AJUSTE.PRODUTO, ESTOQUE_PROD_CTG_AJUSTE.COR_PRODUTO, prd.DESC_PRODUTO, PC.DESC_COR_PRODUTO, PP.PRECO1,
ISNULL(A1,0) F1, 
ISNULL(A2,0) F2, 
ISNULL(A3,0) F3, 
ISNULL(A4,0) F4, 
ISNULL(A5,0) F5, 
ISNULL(A6,0) F6, 
ISNULL(A7,0) F7, 
ISNULL(A8,0) F8, 
ISNULL(A9,0) F9, 
ISNULL(A10,0) F10, 
ISNULL(A11,0) F11, 
ISNULL(A12,0) F12, 
ISNULL(A13,0) F13, 
ISNULL(A14,0) F14, 
ISNULL(A15,0) F15, 
ISNULL(A16,0) F16
from ESTOQUE_PROD_CTG_AJUSTE 
inner join produtos prd
	on prd.PRODUTO = ESTOQUE_PROD_CTG_AJUSTE.PRODUTO
inner join PRODUTO_CORES pc on pc.PRODUTO = ESTOQUE_PROD_CTG_AJUSTE.PRODUTO and pc.COR_PRODUTO = ESTOQUE_PROD_CTG_AJUSTE.COR_PRODUTO
INNER JOIN PRODUTOS_PRECOS PP
	ON PP.PRODUTO = ESTOQUE_PROD_CTG_AJUSTE.PRODUTO AND PP.CODIGO_TAB_PRECO = '00'
where 1=1
and NOME_CONTAGEM = 'SUMARÉ 11-11-2019'
) as p
unpivot
(qtd for POSICAO IN (F1, F2, F3, F4, F5, F6, F7, F8, F9, F10, F11, F12, F13, F14, F15, F16)
) AS unp
LEFT JOIN
	PRODUTOS_BARRA b 
		on b.PRODUTO = unp.PRODUTO and b.COR_PRODUTO = unp.COR_PRODUTO and b.TAMANHO = CAST(SUBSTRING(POSICAO,2,2) AS INT) 
WHERE QTD<0
ORDER BY unp.PRODUTO, unp.COR_PRODUTO


