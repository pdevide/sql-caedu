SELECT CAIXA INTO #CAIXAS FROM FATURAMENTO_PROD WHERE CAIXA IN (
SELECT CAIXA FROM CAEDU_RESERVA_AUTOMATICA WHERE PEDIDO = '216532E')

UPDATE  CAEDU_RESERVA_AUTOMATICA 
SET COR_PRODUTO = '00003'
WHERE PEDIDO = '216532E'
AND CAIXA NOT IN (SELECT CAIXA FROM #CAIXAS)

UPDATE VENDAS_PROD_EMBALADO 
SET COR_PRODUTO = '00003'
WHERE CAIXA IN (
SELECT CAIXA FROM CAEDU_RESERVA_AUTOMATICA WHERE PEDIDO = '216532E' AND COR_PRODUTO = '00003'
)

SELECT * FROM FATURAMENTO_CAIXAS WHERE CAIXA IN (
SELECT CAIXA FROM CAEDU_RESERVA_AUTOMATICA WHERE PEDIDO = '216532E' AND COR_PRODUTO='00003'
)

