CREATE TRIGGER DBO.TGR_CAE_PRODUTOS_FATOR_P 
   ON  DBO.CAE_PRODUTOS_FATOR_P 
   AFTER INSERT
AS 
BEGIN
	
	SET NOCOUNT ON;
	DECLARE @UNOUS_NIVEL_NEW VARCHAR(70), @UNOUS_NIVEL_OLD VARCHAR(70), @CODIGO_FATOR CHAR(6)
    DECLARE @GRIFFE VARCHAR(25), @LINHA VARCHAR(25), @GRUPO_PRODUTO VARCHAR(25), @SUBGRUPO_PRODUTO VARCHAR(25)

	SELECT	@UNOUS_NIVEL_NEW=I.UNOUS_NIVEL, 
			@GRIFFE =I.GRIFFE, 
			@LINHA =I.LINHA, 
			@GRUPO_PRODUTO =I.GRUPO_PRODUTO, 
			@SUBGRUPO_PRODUTO = I.SUBGRUPO_PRODUTO,
			@CODIGO_FATOR = I.CODIGO_FATOR
	FROM INSERTED I

	UPDATE CAE_PRODUTOS_FATOR_P 
	SET UNOUS_NIVEL = 'FATOR_P'
	WHERE CODIGO_FATOR = @CODIGO_FATOR
	
	UPDATE PRODUTOS SET DATA_PARA_TRANSFERENCIA = GETDATE()
	WHERE	
			GRIFFE = @GRIFFE 
			AND LINHA = @LINHA 
			AND GRUPO_PRODUTO = @GRUPO_PRODUTO 
			AND SUBGRUPO_PRODUTO = @SUBGRUPO_PRODUTO

END
GO
