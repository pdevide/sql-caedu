DECLARE @TABPRO TABLE (ID INT IDENTITY(1,1), PRODUTO CHAR(12))
INSERT INTO @TABPRO (PRODUTO)
SELECT PRODUTO FROM @TAB_SKU
GROUP BY PRODUTO

--SELECT * FROM @TABPRO
DECLARE @IPRO INT, @TOTPRO INT, @PRODUTO CHAR(12)
DECLARE @I INT, @TOT2 INT


SELECT @IPRO = MIN(ID), @TOTPRO = MAX(ID)
FROM @TABPRO

WHILE @IPRO <= @TOTPRO
BEGIN
	
	SELECT @PRODUTO = PRODUTO 
	FROM @TABPRO 
	WHERE ID = @IPRO
	
	SET @LISTAPROD = ''
	SELECT @I = MIN(ID), @TOT2 = MAX(ID)
	FROM @TAB_SKU
	WHERE PRODUTO = @PRODUTO

	WHILE @I <= @TOT2
	BEGIN
		SELECT @CODIGO_BARRA = CODIGO_BARRA, @QTD = CONVERT(VARCHAR,QTD)
		FROM @TAB_SKU WHERE ID = @I

		SET	@LISTAPROD = @LISTAPROD + RTRIM(LTRIM(@CODIGO_BARRA)) + ';' + @QTD + '|'

		SET @I = @I + 1
	END

	SET @TAMANHO = LEN(@LISTAPROD)
	IF @TAMANHO > 0
	BEGIN
		SET @LISTAPROD = LEFT(@LISTAPROD, @TAMANHO-1)
		--SELECT @LISTAPROD
		PRINT @PRODUTO

		EXEC CGP_MOVIMENTA_ESTOQUE_FILIAIS 
			'VENDA ATACADO SC', 
			'CD NAVEGANTES', 
			@LISTAPROD, 
			@TRANSFERIDO=0
	END

	SET @IPRO = @IPRO + 1
END