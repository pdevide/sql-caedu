	begin
		select @ERRMSG = 'ERRO AO INSERIR VENDAS_PROD_EMBALADO'
		goto error
	end

	UPDATE A SET A.GERADO = 1
	FROM CAEDU_RESERVA_AUTOMATICA_PACK_WMS A
	JOIN #RESERVA_AUTOMATICA B ON A.DISTRIBUICAO = B.DISTRIBUICAO
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO ATUALIZAR CAEDU_RESERVA_AUTOMATICA_PACK_WMS'
		goto error
	end

	UPDATE A SET A.GERADO = 1
	FROM CAEDU_RESERVA_AUTOMATICA_WMS A
	JOIN #RESERVA_AUTOMATICA B ON A.DISTRIBUICAO = B.DISTRIBUICAO
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO ATUALIZAR CAEDU_RESERVA_AUTOMATICA_WMS'
		goto error
	end

	COMMIT TRANSACTION GERA_VENDAS_WMS
	RETURN

---------------------------------------------------------------------------------------------------------------------------------------
	ERROR:
	
	IF @@TRANCOUNT > 0
		ROLLBACK TRANSACTION GERA_VENDAS_WMS
	IF @ERRMSG IS NOT NULL
	BEGIN
		RAISERROR (@ERRMSG,11,1)
	END	
	
	SET NOCOUNT OFF

END 

