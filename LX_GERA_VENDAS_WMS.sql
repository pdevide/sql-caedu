ALTER PROCEDURE [dbo].[LX_GERA_VENDAS_WMS] ( @DISTRIBUICAO VARCHAR(12) = NULL )
AS
BEGIN 
	DECLARE @ERRMSG varchar(400)

	SET NOCOUNT ON
	
	IF OBJECT_ID('TempDB.dbo.#RESERVA_AUTOMATICA') IS NOT NULL
	BEGIN
		DROP TABLE #RESERVA_AUTOMATICA
	end 

	IF OBJECT_ID('TempDB.dbo.#DISTRIBUICAO_COLETA') IS NOT NULL
	BEGIN
		DROP TABLE #DISTRIBUICAO_COLETA
	end 

	IF OBJECT_ID('TempDB.dbo.#VENDAS') IS NOT NULL
	BEGIN
		DROP TABLE #VENDAS
	end

	IF OBJECT_ID('TempDB.dbo.#FATURAMENTO_CAIXA') IS NOT NULL
	BEGIN
		DROP TABLE #FATURAMENTO_CAIXA
	end

	IF OBJECT_ID('TempDB.dbo.#CAEDU_RESERVA_AUTOMATICA_WMS') IS NOT NULL
	BEGIN
		DROP TABLE #CAEDU_RESERVA_AUTOMATICA_WMS
	end

	IF OBJECT_ID('TempDB.dbo.#VENDAS_PRODUTO') IS NOT NULL
	BEGIN
		DROP TABLE #VENDAS_PRODUTO
	end

	IF OBJECT_ID('TempDB.dbo.#VENDAS_PROD_EMBALADO') IS NOT NULL
	BEGIN
		DROP TABLE #VENDAS_PROD_EMBALADO
	end


	SELECT *, convert(int,null) as COLETA, convert(char(1),null) as PACK1 ,
	ROW_NUMBER() OVER (PARTITION BY DISTRIBUICAO order by DISTRIBUICAO,CAIXA) as COD_RESERVA
	into #RESERVA_AUTOMATICA
	FROM CAEDU_RESERVA_AUTOMATICA_PACK_WMS
	WHERE GERADO = 0 AND (DISTRIBUICAO = @DISTRIBUICAO OR @DISTRIBUICAO is null)

	select ID_COLETA,DISTRIBUICAO,PRODUTO,QTDE, substring(CAIXA,1,1) as PACK,
	ROW_NUMBER() OVER (PARTITION BY DISTRIBUICAO order by DISTRIBUICAO,ID_COLETA) as COD_COLETA
	into #DISTRIBUICAO_COLETA
	FROM PDA_WMS_TB_DISTRIBUICAO_COLETA
	WHERE DISTRIBUICAO = @DISTRIBUICAO

	---COMANDO ORIGINAL - SUPRIMIDO O CAMPO PACK ABAIXO
	--UPDATE A SET A.PACK = B.PACK,  
	--A.COLETA = B.ID_COLETA
	--FROM #RESERVA_AUTOMATICA A
	--JOIN #DISTRIBUICAO_COLETA B ON A.DISTRIBUICAO = B.DISTRIBUICAO AND A.COD_RESERVA = B.COD_COLETA 

	UPDATE A SET
	A.COLETA = B.ID_COLETA
	FROM #RESERVA_AUTOMATICA A
	JOIN #DISTRIBUICAO_COLETA B ON A.DISTRIBUICAO = B.DISTRIBUICAO AND A.COD_RESERVA = B.COD_COLETA 

	DELETE #RESERVA_AUTOMATICA WHERE COLETA IS NULL



	SELECT DISTINCT A.VENDA AS PEDIDO,Isnull(RTRIM(LTRIM(DBO.FX_PARAMETRO('COLECAO_PADRAO'))),'') AS COLECAO,
	ISNULL(DBO.FX_PARAMETRO_EMPRESA('TABELA_PRECO_PADRAO',0),'') AS CODIGO_TAB_PRECO,ISNULL(DBO.FX_PARAMETRO_EMPRESA('TIPO_VENDA',0),'') AS TIPO,
	convert(varchar(8),getdate(),112) as DATA_RECEBIMENTO,ISNULL(DBO.FX_PARAMETRO_EMPRESA('COND_PGTO_PADRAO',0),'') AS CONDICAO_PGTO, 
	A.FILIAL_ORIGEM AS FILIAL, A.FILIAL AS CLIENTE_ATACADO,ISNULL(B.TRANSPORTADORA,ISNULL(DBO.FX_PARAMETRO_EMPRESA('TRANSPORTADORA_PADRAO',0),'')) AS TRANSPORTADORA,
	ISNULL(DBO.FX_PARAMETRO_EMPRESA('MOEDA_PADRAO',0),'') AS MOEDA,convert(varchar(8),getdate(),112) as EMISSAO,
	(CASE WHEN ISNULL(DBO.FX_PARAMETRO_EMPRESA('CTRL_MULT_ENTREGAS',0),'.F.') = '.T.' THEN 1 ELSE 0 END) AS CTRL_MULT_ENTREGAS,
	convert(char(1),null) as APROVACAO,'VENDAS_PRODUTO' AS TABELA_FILHA,convert(varchar(8),getdate(),112) as CADASTRAMENTO,100 AS ACEITA_PECAS_PEQUENAS, 100 AS ACEITA_PECAS_COM_CORTE,
	' ' AS APROVADO_POR,A.FILIAL AS REPRESENTANTE, A.FILIAL AS GERENTE, 1 as ENTREGA_CIF,FILIAL_ORIGEM AS FILIAL_DIGITACAO, A.FILIAL AS NOME_CLIFOR_ENTREGA,
	convert(numeric(12,2),null) as TOT_VALOR_ENTREGAR, convert(numeric(12,2),null) as TOT_VALOR_ORIGINAL,
	convert(int,null) as TOT_QTDE_ENTREGAR, convert(int,null) as TOT_QTDE_ORIGINAL
	into #VENDAS
	FROM #RESERVA_AUTOMATICA A
	LEFT JOIN CLIENTES_ATACADO B ON A.FILIAL = B.CLIENTE_ATACADO

	UPDATE #VENDAS SET APROVACAO = VENDAS_TIPO.APROVACAO 
	FROM #VENDAS
	JOIN VENDAS_TIPO ON #VENDAS.TIPO = VENDAS_TIPO.TIPO 

