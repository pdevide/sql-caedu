								VE15, VE16, VE17, VE18, VE19, VE20, VE21, VE22, VE23, VE24, VE25, VE26, VE27, VE28, VE29, VE30, VE31, VE32, VE33, VE34, VE35, 
								VE36, VE37, VE38, VE39, VE40, VE41, VE42, VE43, VE44, VE45, VE46, VE47, VE48, ITEM_PEDIDO) 
	select  PEDIDO , PRODUTO, COR_PRODUTO, ENTREGA, LIMITE_ENTREGA, 
			QTDE_ORIGINAL, QTDE_ENTREGAR, VALOR_ORIGINAL, VALOR_ENTREGAR, PRECO1,PRECO2, PRECO3, PRECO4, 
			VO1, VO2, VO3, VO4, VO5, VO6, VO7, VO8, VO9, VO10, VO11, VO12, VO13, VO14, VO15, VO16, VO17, VO18, VO19, VO20, 
			VO21, VO22, VO23, VO24, VO25, VO26, VO27, VO28, VO29, VO30, VO31, VO32, VO33, VO34, VO35, VO36, VO37, VO38, VO39, VO40, VO41, 
			VO42, VO43, VO44, VO45, VO46, VO47, VO48, VE1,  VE2,  VE3,  VE4,  VE5,  VE6,  VE7,  VE8,  VE9,  VE10, VE11, VE12, VE13, VE14, 
			VE15, VE16, VE17, VE18, VE19, VE20, VE21, VE22, VE23, VE24, VE25, VE26, VE27, VE28, VE29, VE30, VE31, VE32, VE33, VE34, VE35, 
			VE36, VE37, VE38, VE39, VE40, VE41, VE42, VE43, VE44, VE45, VE46, VE47, VE48, ITEM_PEDIDO
	from #VENDAS_PRODUTO 
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO INSERIR VENDAS_PRODUTO '
		goto error
	end

	INSERT INTO VENDAS_PROD_EMBALADO (CAIXA_FECHADA, CAIXA, NOME_CLIFOR, PEDIDO,ENTREGA,PRODUTO,COR_PRODUTO,QTDE_EMBALADA,
										E1, E2,E3, E4,E5, E6,E7, E8, E9, E10,E11,E12, E13,E14,E15,E16, E17,E18,E19,E20, E21,E22,E23,E24,
										E25,E26,E27,E28, E29,E30,E31,E32, E33,E34,E35,E36, E37,E38,E39,E40, E41,E42,E43,E44,E45,E46,E47,E48,
										ITEM,PRECO1,VALOR_EMBALADO,FILIAL,PEDIDO_PRODUTO,PEDIDO_COR_PRODUTO,ORIGEM,MATA_SALDO,ITEM_PEDIDO,REPRESENTANTE) 
	select	1 as CAIXA_FECHADA, CAIXA, NOME_CLIFOR, PEDIDO,ENTREGA,PRODUTO,COR_PRODUTO,QTDE_EMBALADA,
			E1, E2,E3, E4,E5, E6,E7, E8, E9, E10,E11,E12, E13,E14,E15,E16, E17,E18,E19,E20, E21,E22,E23,E24,
