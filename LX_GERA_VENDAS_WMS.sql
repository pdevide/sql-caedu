	INTO #FATURAMENTO_CAIXA
	FROM #RESERVA_AUTOMATICA 


	select ROW_NUMBER() OVER (ORDER BY DISTRIBUICAO) AS CHAVE,
	DISTRIBUICAO,A.PRODUTO,COR_PRODUTO,FILIAL,FILIAL_ORIGEM,QTDE_TOTAL,
	Q1,Q2,Q3,Q4,Q5,Q6,Q7,Q8,Q9,Q10,Q11,Q12,Q13,Q14,Q15,Q16,Q17,Q18,Q19,Q20,Q21,Q22,Q23,Q24,
	Q25,Q26,Q27,Q28,Q29,Q30,Q31,Q32,Q33,Q34,Q35,Q36,Q37,Q38,Q39,Q40,Q41,Q42,Q43,Q44,Q45,Q46,Q47,Q48,
	DATA,QTDE_PACK,CAIXA,VENDA,ROMANEIO,GERADO,CODIGO,ROMANEIO_PRODUTO, COD_RESERVA
	into #CAEDU_RESERVA_AUTOMATICA_WMS
	FROM #RESERVA_AUTOMATICA A
	JOIN PRODUTOS_PACKS_PERMITIDOS B ON A.PRODUTO = B.PRODUTO AND A.PACK = B.PACK 


	SELECT VENDA AS PEDIDO , A.PRODUTO, A.COR_PRODUTO, CONVERT(VARCHAR(8),GETDATE(),112) AS ENTREGA, CONVERT(VARCHAR(8),GETDATE(),112) AS LIMITE_ENTREGA, 
	QTDE_TOTAL AS QTDE_ORIGINAL, QTDE_TOTAL AS QTDE_ENTREGAR, 
	convert(numeric(12,2),null) as VALOR_ORIGINAL, convert(numeric(12,2),null) as VALOR_ENTREGAR,
	ISNULL(CASE WHEN b.VARIA_PRECO_COR = 0 THEN c.PRECO1 ELSE d.PRECO1 END,0) AS PRECO1,ISNULL(CASE WHEN b.VARIA_PRECO_COR = 0 THEN c.PRECO2 ELSE d.PRECO2 END,0) AS PRECO2,
	ISNULL(CASE WHEN b.VARIA_PRECO_COR = 0 THEN c.PRECO3 ELSE d.PRECO3 END,0) AS PRECO3,ISNULL(CASE WHEN b.VARIA_PRECO_COR = 0 THEN c.PRECO4 ELSE d.PRECO4 END,0) AS PRECO4,
	Q1 as VO1, Q2 AS VO2, Q3 AS VO3, Q4 AS VO4, Q5 AS VO5, Q6 AS VO6, Q7 AS VO7, Q8 AS VO8, Q9 AS VO9, Q10 AS VO10, Q11 AS VO11, Q12 AS VO12, 
	Q13 AS VO13, Q14 AS VO14, Q15 AS VO15, Q16 AS VO16, Q17 AS VO17, Q18 AS VO18, Q19 AS VO19, Q20 AS VO20, Q21 AS VO21, Q22 AS VO22, Q23 AS VO23, Q24 AS VO24, 
	Q25 AS VO25, Q26 AS VO26, Q27 AS VO27, Q28 AS VO28, Q29 AS VO29, Q30 AS VO30, Q31 AS VO31, Q32 AS VO32, Q33 AS VO33, Q34 AS VO34, Q35 AS VO35, Q36 AS VO36, 
	Q37 AS VO37, Q38 AS VO38, Q39 AS VO39, Q40 AS VO40, Q41 AS VO41, Q42 AS VO42, Q43 AS VO43, Q44 AS VO44, Q45 AS VO45, Q46 AS VO46, Q47 AS VO47, Q48 AS VO48, 
	Q1 AS VE1,  Q2 AS VE2,  Q3 AS VE3,  Q4 AS VE4,  Q5 AS VE5,  Q6 AS VE6,  Q7 AS VE7,  Q8 AS VE8,  Q9 AS VE9,  Q10 AS VE10, Q11 AS VE11, Q12 AS VE12, 
	Q13 AS VE13, Q14 AS VE14, Q15 AS VE15, Q16 AS VE16, Q17 AS VE17, Q18 AS VE18, Q19 AS VE19, Q20 AS VE20, Q21 AS VE21, Q22 AS VE22, Q23 AS VE23, Q24 AS VE24, 
	Q25 AS VE25, Q26 AS VE26, Q27 AS VE27, Q28 AS VE28, Q29 AS VE29, Q30 AS VE30, Q31 AS VE31, Q32 AS VE32, Q33 AS VE33, Q34 AS VE34, Q35 AS VE35, Q36 AS VE36, 
	Q37 AS VE37, Q38 AS VE38, Q39 AS VE39, Q40 AS VE40, Q41 AS VE41, Q42 AS VE42, Q43 AS VE43, Q44 AS VE44, Q45 AS VE45, Q46 AS VE46, Q47 AS VE47, Q48 AS VE48,'0000' as ITEM_PEDIDO
	INTO #VENDAS_PRODUTO
	FROM #CAEDU_RESERVA_AUTOMATICA_WMS A
	JOIN #VENDAS V ON A.VENDA = V.PEDIDO
	JOIN PRODUTOS B ON A.PRODUTO = B.PRODUTO
	LEFT JOIN PRODUTOS_PRECOS C ON A.PRODUTO = C.PRODUTO AND V.CODIGO_TAB_PRECO = C.CODIGO_TAB_PRECO
	LEFT JOIN PRODUTOS_PRECO_COR D ON A.PRODUTO =D.PRODUTO AND A.COR_PRODUTO = D.COR_PRODUTO AND V.CODIGO_TAB_PRECO = D.CODIGO_TAB_PRECO 

	UPDATE #VENDAS_PRODUTO SET VALOR_ORIGINAL = QTDE_ORIGINAL * PRECO1, VALOR_ENTREGAR = QTDE_ENTREGAR * PRECO1

	UPDATE A SET A.TOT_VALOR_ENTREGAR = B.TOT_VALOR_ORIGINAL, A.TOT_VALOR_ORIGINAL = B.TOT_VALOR_ORIGINAL, 
	A.TOT_QTDE_ENTREGAR = B.TOT_QTDE_ORIGINAL, A.TOT_QTDE_ORIGINAL = B.TOT_QTDE_ORIGINAL
	FROM #VENDAS A
	JOIN (SELECT PEDIDO, SUM(VALOR_ORIGINAL) AS TOT_VALOR_ORIGINAL, SUM(QTDE_ORIGINAL) AS TOT_QTDE_ORIGINAL
			FROM #VENDAS_PRODUTO GROUP BY PEDIDO ) B ON A.PEDIDO = B.PEDIDO



	SELECT A.CHAVE,
	1 AS CAIXA_FECHADA, a.CAIXA, a.FILIAL AS NOME_CLIFOR, VENDA AS PEDIDO, CONVERT(VARCHAR(8),GETDATE(),112) AS ENTREGA,
	a.PRODUTO, a.COR_PRODUTO, a.QTDE_TOTAL as QTDE_EMBALADA, b.VALOR_ENTREGAR as VALOR_EMBALADO,
	Q1 AS E1, Q2 AS E2, Q3 AS E3, Q4 AS E4, Q5 AS E5, Q6 AS E6, Q7 AS E7, Q8 AS E8, Q9 AS E9, Q10 AS E10, Q11 AS E11, Q12 AS E12, 
	Q13 AS E13, Q14 AS E14, Q15 AS E15, Q16 AS E16, Q17 AS E17, Q18 AS E18, Q19 AS E19, Q20 AS E20, Q21 AS E21, Q22 AS E22, Q23 AS E23, Q24 AS E24, 
	Q25 AS E25, Q26 AS E26, Q27 AS E27, Q28 AS E28, Q29 AS E29, Q30 AS E30, Q31 AS E31, Q32 AS E32, Q33 AS E33, Q34 AS E34, Q35 AS E35, Q36 AS E36, 
	Q37 AS E37, Q38 AS E38, Q39 AS E39, Q40 AS E40, Q41 AS E41, Q42 AS E42, Q43 AS E43, Q44 AS E44, Q45 AS E45, Q46 AS E46, Q47 AS E47, Q48 AS E48, 
	/*right('000000'+ltrim(convert(varchar(6),ROW_NUMBER() OVER (PARTITION BY A.FILIAL, A.PRODUTO, A.COR_PRODUTO order by A.FILIAL, A.PRODUTO, A.COR_PRODUTO,CAIXA))),6) as ITEM, */
	isnull( dbo.FX_PROXIMO_ITEM_PROD_EMBALADO(a.FILIAL,a.PRODUTO,a.COR_PRODUTO,'CD REGIS'), right(a.CAIXA,6)) AS ITEM,
	b.PRECO1, b.QTDE_ENTREGAR , a.FILIAL_ORIGEM as FILIAL,
	a.produto as PEDIDO_PRODUTO,a.COR_PRODUTO as PEDIDO_COR_PRODUTO,'S' AS ORIGEM,0 AS MATA_SALDO,B.ITEM_PEDIDO, A.FILIAL AS REPRESENTANTE
	INTO #VENDAS_PROD_EMBALADO
	FROM #CAEDU_RESERVA_AUTOMATICA_WMS  A
	JOIN #VENDAS_PRODUTO  B ON A.VENDA = PEDIDO AND A.PRODUTO = B.PRODUTO AND A.COR_PRODUTO = B.COR_PRODUTO

	DECLARE @TOTLINHAS INT, @I INT
	SET @I=1
	SELECT @TOTLINHAS = COUNT(*) FROM #VENDAS_PROD_EMBALADO

	WHILE @I <= @TOTLINHAS
	BEGIN
	   UPDATE #VENDAS_PROD_EMBALADO 
	   SET ITEM = RIGHT(REPLACE(CONVERT(VARCHAR,GETDATE(),114),':',''),6)
	   WHERE CHAVE = @I
	   -- ESPERA 50 MILESIMOS DE SEGUNDO
	   WAITFOR DELAY '00:00:00:50'
	   SET @I = @I + 1
	END


	BEGIN TRANSACTION GERA_VENDAS_WMS

	insert into CAEDU_RESERVA_AUTOMATICA_WMS (	DISTRIBUICAO,PRODUTO,COR_PRODUTO,FILIAL,FILIAL_ORIGEM,QTDE_TOTAL,
												Q1,Q2,Q3,Q4,Q5,Q6,Q7,Q8,Q9,Q10,Q11,Q12,Q13,Q14,Q15,Q16,Q17,Q18,Q19,Q20,Q21,Q22,Q23,Q24,
												Q25,Q26,Q27,Q28,Q29,Q30,Q31,Q32,Q33,Q34,Q35,Q36,Q37,Q38,Q39,Q40,Q41,Q42,Q43,Q44,Q45,Q46,Q47,Q48,
												DATA,QTDE_PACK,CAIXA,VENDA,ROMANEIO,GERADO,CODIGO,ROMANEIO_PRODUTO)
	select DISTRIBUICAO,PRODUTO,COR_PRODUTO,FILIAL,FILIAL_ORIGEM,QTDE_TOTAL,
			Q1,Q2,Q3,Q4,Q5,Q6,Q7,Q8,Q9,Q10,Q11,Q12,Q13,Q14,Q15,Q16,Q17,Q18,Q19,Q20,Q21,Q22,Q23,Q24,
			Q25,Q26,Q27,Q28,Q29,Q30,Q31,Q32,Q33,Q34,Q35,Q36,Q37,Q38,Q39,Q40,Q41,Q42,Q43,Q44,Q45,Q46,Q47,Q48,
			DATA,QTDE_PACK,CAIXA,VENDA,ROMANEIO,GERADO,CODIGO,ROMANEIO_PRODUTO
	from #CAEDU_RESERVA_AUTOMATICA_WMS
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO INSERIR CAEDU_RESERVA_AUTOMATICA_WMS'
		goto error
	end

	Insert Into VENDAS (PEDIDO, COLECAO, CODIGO_TAB_PRECO, TIPO, DATA_RECEBIMENTO, CONDICAO_PGTO, FILIAL, CLIENTE_ATACADO, TRANSPORTADORA, 
						MOEDA, EMISSAO, CTRL_MULT_ENTREGAS, APROVACAO, TABELA_FILHA,CADASTRAMENTO, ACEITA_PECAS_PEQUENAS, 
						ACEITA_PECAS_COM_CORTE, APROVADO_POR, REPRESENTANTE, GERENTE,ENTREGA_CIF,FILIAL_DIGITACAO,NOME_CLIFOR_ENTREGA,
						TOT_VALOR_ENTREGAR, TOT_VALOR_ORIGINAL,	TOT_QTDE_ENTREGAR, TOT_QTDE_ORIGINAL) 
	select	PEDIDO, COLECAO, CODIGO_TAB_PRECO, TIPO, DATA_RECEBIMENTO, CONDICAO_PGTO, FILIAL, CLIENTE_ATACADO, TRANSPORTADORA, 
			MOEDA, EMISSAO, CTRL_MULT_ENTREGAS, APROVACAO, TABELA_FILHA,CADASTRAMENTO, ACEITA_PECAS_PEQUENAS, 
			ACEITA_PECAS_COM_CORTE, APROVADO_POR, REPRESENTANTE, GERENTE,ENTREGA_CIF,FILIAL_DIGITACAO,NOME_CLIFOR_ENTREGA,
			TOT_VALOR_ENTREGAR, TOT_VALOR_ORIGINAL,	TOT_QTDE_ENTREGAR, TOT_QTDE_ORIGINAL 
	from #VENDAS 
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO INSERIR VENDAS'
		goto error
	end

	INSERT INTO FATURAMENTO_CAIXAS (CAIXA,NOME_CLIFOR,PESO_BRUTO_CAIXA,PESO_LIQUIDO_CAIXA,DATA_EMBALAGEM,EMBALADOR,
									QTDE_CAIXA, TIPO_CAIXA,NOME_CLIFOR_ENTREGA,CAIXA_FECHADA)
	select	CAIXA,NOME_CLIFOR,PESO_BRUTO_CAIXA,PESO_LIQUIDO_CAIXA,DATA_EMBALAGEM,EMBALADOR,
			QTDE_CAIXA, TIPO_CAIXA,NOME_CLIFOR_ENTREGA,1 as CAIXA_FECHADA
	from #FATURAMENTO_CAIXA 
	IF @@ERROR <> 0 
	begin
		select @ERRMSG = 'ERRO AO INSERIR FATURAMENTO_CAIXAS'
		goto error
	end

	INSERT INTO VENDAS_PRODUTO (PEDIDO , PRODUTO, COR_PRODUTO, ENTREGA, LIMITE_ENTREGA, 
								QTDE_ORIGINAL, QTDE_ENTREGAR, VALOR_ORIGINAL, VALOR_ENTREGAR, PRECO1,PRECO2, PRECO3, PRECO4, 
								VO1, VO2, VO3, VO4, VO5, VO6, VO7, VO8, VO9, VO10, VO11, VO12, VO13, VO14, VO15, VO16, VO17, VO18, VO19, VO20, 
								VO21, VO22, VO23, VO24, VO25, VO26, VO27, VO28, VO29, VO30, VO31, VO32, VO33, VO34, VO35, VO36, VO37, VO38, VO39, VO40, VO41, 
